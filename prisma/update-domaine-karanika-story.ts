// Κείμενο story για το Domaine Karanika, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στο Αμύνταιο, στη βορειοδυτική Ελλάδα, το Domaine Karanika αποτελεί ένα οινοποιείο αφιερωμένο στην έκφραση του αμπελώνα μέσα από μια ιδιαίτερα φυσική και χειροποίητη προσέγγιση. Ιδρύθηκε από τον Laurens Karanika και την Annette van Kampen, οι οποίοι εγκατέλειψαν την προηγούμενη επαγγελματική τους πορεία για να ακολουθήσουν το κοινό τους όραμα για οργανικά αφρώδη κρασιά υψηλής ποιότητας.",
  "Οι αμπελώνες του κτήματος καλλιεργούνται με οργανικές και βιοδυναμικές πρακτικές, με επίκεντρο παλιές, αυτόριζες φυτεύσεις Ξινόμαυρου, αλλά και Ασύρτικο και Λημνιώνα. Η οινοποίηση βασίζεται στη χαμηλή παρέμβαση, στις γηγενείς ζύμες και στη χειρωνακτική διαχείριση του σταφυλιού, ενώ για τα αφρώδη εφαρμόζεται η παραδοσιακή μέθοδος δεύτερης ζύμωσης στη φιάλη.",
  "Το Ξινόμαυρο βρίσκεται στον πυρήνα της ταυτότητας του Domaine Karanika, εκφρασμένο τόσο μέσα από ήσυχα όσο και μέσα από αφρώδη κρασιά. Η φιλοσοφία τους είναι ξεκάθαρη: σεβασμός στη γη, ελάχιστη παρέμβαση και κρασιά που αφήνουν τον τόπο και την ποικιλία να μιλήσουν.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "domaine-karanika" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
