// Κείμενο story + philosophy για το Boutari, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Η ιστορία της Boutari ξεκινά το 1879 στη Νάουσα, όταν ο Ιωάννης Μπουτάρης ιδρύει την οινοποιία που θα εξελιχθεί σε ένα από τα πιο αναγνωρίσιμα ονόματα του ελληνικού κρασιού. Το 1906 δημιουργείται το πρώτο ιδιόκτητο οινοποιείο και κάβα λιανικής στη Νάουσα, ενώ το 1935 ξεκινούν οι πρώτες εξαγωγές προς την Αυστρία, την Ουγγαρία και την Αίγυπτο.",
  "Η σχέση της Boutari με τον ελληνικό αμπελώνα ενισχύεται ιδιαίτερα από τη δεκαετία του 1960, όταν η εταιρεία αποκτά τον πρώτο της ιδιόκτητο αμπελώνα στο Γιαννακοχώρι. Ακολουθεί μια περίοδος μεγάλης ανάπτυξης, με οινοποιεία και αμπελώνες σε σημαντικές ζώνες όπως η Νάουσα, η Γουμένισσα, η Σαντορίνη, η Μαντινεία και η Κρήτη.",
  "Παράλληλα, η Boutari επένδυσε νωρίς στον οινοτουρισμό, ανοίγοντας από το 1989 το οινοποιείο της Σαντορίνης στο κοινό. Η εταιρεία συνέβαλε επίσης στην ανάδειξη ποικιλιών όπως το Ξινόμαυρο και το Μοσχοφίλερο, ενώ ανέπτυξε ένα ευρύ portfolio ελληνικών και διεθνών ποικιλιών.",
  "Σήμερα, η Boutari συνεχίζει την πορεία της μέσα από μια νέα εταιρική εποχή, διατηρώντας ως βασικό σημείο αναφοράς την ιστορική της κληρονομιά και τη σχέση της με τον ελληνικό αμπελώνα.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία της Boutari βασίζεται στην ιδέα ότι η σύγχρονη οινοποίηση πρέπει να εξελίσσεται χωρίς να απομακρύνεται από τον τόπο και τις ποικιλίες που αποτελούν τη βάση του ελληνικού αμπελώνα.",
  "Η εταιρεία δραστηριοποιείται σε διαφορετικές οινοπαραγωγικές ζώνες της Ελλάδας, με στόχο να αναδεικνύει τις ιδιαιτερότητες κάθε περιοχής. Στη Νάουσα, το Ξινόμαυρο αποτελεί βασικό σημείο αναφοράς, ενώ στη Μαντινεία η Boutari έχει συνδέσει την παρουσία της με τη διατήρηση και ανάδειξη του Μοσχοφίλερου. Παράλληλα, η Σαντορίνη, η Γουμένισσα και η Κρήτη αποτελούν σημαντικούς σταθμούς της οινοποιητικής της δραστηριότητας.",
  "Στον αμπελώνα εφαρμόζονται αρχές βιολογικής γεωργίας και πρακτικές που στοχεύουν στη διατήρηση της βιοποικιλότητας και στη μείωση του περιβαλλοντικού αποτυπώματος. Η προσέγγιση αντιμετωπίζει το αμπέλι ως μέρος ενός ευρύτερου οικοσυστήματος και δίνει έμφαση στη διατήρηση και ενίσχυση παλαιών αμπελώνων.",
  "Έτσι, η σύγχρονη Boutari συνδυάζει την ιστορική της εμπειρία με την εξέλιξη της αμπελουργίας και της οινοποίησης, επιδιώκοντας κρασιά με σαφή ποικιλιακό και τοπικό χαρακτήρα.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "boutari" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
