// Κείμενο story για το Winery Monsieur Nicolas (Γ. Καραμήτρος), δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στον Μεσενικόλα Καρδίτσας, κάτω από τα Άγραφα και δίπλα στη λίμνη Πλαστήρα, το Winery Monsieur Nicolas αποτελεί τη σύγχρονη συνέχεια μιας οικογένειας με τέσσερις γενιές αφοσίωσης στην αμπελουργία. Η σχέση της οικογένειας Καραμήτρου με τον τόπο ξεκινά περισσότερο από έναν αιώνα πριν, ενώ το 2000 ο Γιώργος Καραμήτρος ιδρύει το σύγχρονο οινοποιείο, επιλέγοντας να εξελίξει την οικογενειακή παράδοση μέσα από τη σύγχρονη οινοποίηση.",
  "Το κτήμα διαθέτει 110 στρέμματα ιδιόκτητων αμπελώνων και συνεργάζεται με περίπου 300 αμπελουργούς της περιοχής. Στο επίκεντρο βρίσκεται το Μαύρο Μεσενικόλα, μια σπάνια τοπική ποικιλία που συνδέεται άμεσα με την οινική ταυτότητα της περιοχής και αποτελεί βασικό άξονα της προσπάθειας του οινοποιείου να αναδείξει τον Μεσενικόλα πέρα από τα όρια της Θεσσαλίας.",
  "Παράλληλα, το Μπατίκι, ο Λημνιώνας και διεθνείς ποικιλίες όπως το Syrah, το Carignan και το Chardonnay συμπληρώνουν το portfolio. Η φιλοσοφία του Γιώργου Καραμήτρου συνοψίζεται στην ιδέα μιας «νέας παράδοσης»: τεχνολογία και καινοτομία, χωρίς να χάνεται η σχέση με τον τόπο, την ιστορία και τις τοπικές ποικιλίες.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "winery-monsieur-nicolas" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
