// Κείμενο story + philosophy για το Acra Winery, δόθηκε αυτούσιο από τον χρήστη.
// Χωρισμένο σε δύο πεδία: story (ίδρυση, αμπελώνας, ποικιλίες) και
// philosophy (η ρητή δήλωση φιλοσοφίας οινοποίησης στο τέλος του κειμένου).
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Το Acra Winery δημιουργήθηκε το 2021 στη Νεμέα Κορινθίας από τον χημικό–οινολόγο Σπύρο Παπανδρέου και τον μηχανολόγο μηχανικό Δημήτρη Παπανδρέου. Πρόκειται για ένα νέο οινοποιείο που γεννήθηκε μέσα σε μία από τις πιο ιστορικές αμπελουργικές ζώνες της Ελλάδας, με στόχο να εξερευνήσει τη Νεμέα μέσα από μια σύγχρονη και ιδιαίτερα εστιασμένη ματιά.",
  "Η προσέγγιση του Acra ξεκινά από τον αμπελώνα. Οι επιλεγμένες αμπελουργικές εκτάσεις βρίσκονται σε διαφορετικά υψόμετρα και εδαφικά περιβάλλοντα της ζώνης, επιτρέποντας στους δύο δημιουργούς να μελετούν και να αποτυπώνουν τις διαφορές κάθε αμπελοτεμαχίου. Η καλλιέργεια ακολουθεί πρακτικές με έμφαση στον σεβασμό του αμπελώνα και στη σταθερότητα της πρώτης ύλης.",
  "Από το Αγιωργίτικο και την Κυδωνίτσα μέχρι το Ασύρτικο και το Malbec, κάθε ποικιλία αντιμετωπίζεται ξεχωριστά. Η παραγωγή παραμένει μικρή και εστιασμένη, με τέσσερις βασικές ετικέτες, ώστε η προσοχή να παραμένει στην ακρίβεια και στην καθαρή έκφραση του κάθε κρασιού.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία του Acra βασίζεται στην ιδέα ότι κάθε κρασί πρέπει να εκφράζει με καθαρότητα τρία στοιχεία: την ποικιλία, τον αμπελώνα και το μικροκλίμα του τόπου. Για αυτό το οινοποιείο επιλέγει κυρίως μονοποικιλιακές οινοποιήσεις και εφαρμόζει μόνο τις απαραίτητες οινολογικές παρεμβάσεις, με στόχο να διατηρείται ο χαρακτήρας του σταφυλιού και η ιδιαιτερότητα κάθε αμπελοτεμαχίου.",
  "Στη Νεμέα, το Αγιωργίτικο αποτελεί βασικό σημείο αναφοράς, ενώ παράλληλα το Acra εξερευνά ελληνικές και διεθνείς ποικιλίες όπως το Ασύρτικο, η Κυδωνίτσα και το Malbec. Η προσέγγιση συνδυάζει σύγχρονη επιστημονική γνώση με σεβασμό στην παράδοση και στο φυσικό περιβάλλον, χωρίς να επιδιώκει να καλύψει τον τόπο πίσω από την τεχνολογία.",
  "Στόχος είναι κάθε ετικέτα να λειτουργεί ως μια καθαρή αποτύπωση του συγκεκριμένου αμπελώνα και της ποικιλίας του — ένα κρασί με σαφή ταυτότητα, ακρίβεια και αίσθηση τόπου.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "acra-winery" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
