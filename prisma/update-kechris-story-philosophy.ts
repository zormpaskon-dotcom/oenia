// Κείμενο story + philosophy για το Kechris Winery, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Η ιστορία της Kechris είναι άρρηκτα συνδεδεμένη με τη Θεσσαλονίκη και με ένα από τα πιο χαρακτηριστικά ελληνικά κρασιά: τη ρετσίνα. Η οικογένεια ξεκίνησε την οινοποιητική της δραστηριότητα στις αρχές του 20ού αιώνα και δημιούργησε την οικογενειακή επιχείρηση στο Καλοχώρι Θεσσαλονίκης. Εκεί αναπτύχθηκε η παραγωγή κρασιών και ποτών, ενώ σταδιακά η ρετσίνα απέκτησε κεντρική θέση στην πορεία της οικογένειας.",
  "Το Κεχριμπάρι γεννήθηκε αρχικά στην οικογενειακή ταβέρνα «Κόκορας» στην παλιά Θεσσαλονίκη και η φήμη του εξαπλώθηκε γρήγορα. Η οικογένεια επένδυσε στη συνέχεια στην εμφιάλωση και στην εξέλιξη της ρετσίνας, δημιουργώντας το χαρακτηριστικό πράσινο καραφάκι που συνδέθηκε με το κρασί.",
  "Η Kechris συμμετείχε επίσης στην ίδρυση της Ένωσης Οινοπαραγωγών του Αμπελώνα της Μακεδονίας, ενώ με την πάροδο των χρόνων ανέπτυξε ένα σύγχρονο οινοποιείο και διεύρυνε την παραγωγή της πέρα από τη ρετσίνα. Σήμερα, η παράδοση συνυπάρχει με την έρευνα και την καινοτομία, μέσα από μια γκάμα που περιλαμβάνει ρετσίνες, Ξινόμαυρο και κρασιά από ελληνικές και διεθνείς ποικιλίες.",
].join("\n\n");

const PHILOSOPHY = [
  "Για την Kechris, η παράδοση δεν αποτελεί κάτι στατικό. Η φιλοσοφία του οινοποιείου βασίζεται στην προσπάθεια να εξελίσσει ένα αυθεντικά ελληνικό προϊόν χωρίς να χάνει τη σύνδεσή του με την ιστορία και την ταυτότητά του. Η ρετσίνα βρίσκεται στο επίκεντρο αυτής της προσέγγισης: η οικογένεια επένδυσε στην επιστημονική γνώση και στη σύγχρονη οινοποίηση για να εξερευνήσει διαφορετικές εκφράσεις της, από το Κεχριμπάρι έως το Tear of the Pine και το Afros, την πρώτη pet-nat ρετσίνα της σειράς.",
  "Η προσέγγιση στο οινοποιείο είναι τεχνικά ακριβής αλλά προσαρμοσμένη στον χαρακτήρα κάθε κρασιού. Τα σταφύλια συλλέγονται χειρωνακτικά και μεταφέρονται σε μικρά τελάρα, ενώ η οινοποίηση πραγματοποιείται σε ανοξείδωτες δεξαμενές ή δρύινα βαρέλια, ανάλογα με την ποικιλία και το επιθυμητό στυλ. Στη ρετσίνα, η ρητίνη προστίθεται στην αρχή της ζύμωσης και στη συνέχεια απομακρύνεται, ώστε να παραμείνουν στο κρασί κυρίως τα καθαρά και ποιοτικά αρωματικά της στοιχεία.",
  "Πέρα από την τεχνική, η Kechris αντιμετωπίζει το κρασί ως μέρος της ελληνικής κουλτούρας και της κοινωνικής ζωής. Η «αμεσότητα» —η ειλικρίνεια, η αυθεντικότητα και η ανθρώπινη σχέση— αποτελεί μία από τις βασικές αξίες της οικογένειας.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "kechris" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
