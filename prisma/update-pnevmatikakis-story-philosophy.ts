// Κείμενο story + philosophy για το Pnevmatikakis Winery, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στον Δραπανιά Κισσάμου, στα Χανιά, η Pnevmatikakis Winery συνεχίζει μια οικογενειακή σχέση με το κρασί που ξεκινά αρκετές γενιές πίσω. Η οινοποιητική παράδοση της οικογένειας ξεκίνησε στην Ποταμίδα Κισσάμου, ενώ το 2007 δημιουργήθηκε το σύγχρονο οινοποιείο στον Δραπανιά, μαζί με πέτρινη κάβα και Μουσείο Οίνου.",
  "Η νέα εγκατάσταση σχεδιάστηκε ώστε η οικογενειακή γνώση να συναντήσει τη σύγχρονη τεχνολογία. Σήμερα η Pnevmatikakis διαθέτει αμπελώνες περίπου 110 στρεμμάτων, ενώ συνεργάζεται παράλληλα με μικρότερους τοπικούς παραγωγούς που προμηθεύουν σταφύλια από την Κρήτη. Η παραγωγή περιλαμβάνει λευκά, ερυθρά και ροζέ κρασιά, από μονοποικιλιακές εμφιαλώσεις έως blends.",
  "Σημαντικό μέρος της ταυτότητας του οινοποιείου αποτελεί η σύνδεση με τον κρητικό αμπελώνα. Στις ποικιλίες περιλαμβάνονται Βιδιανό, Βηλάνα, Πλυτό, Λιάτικο, Κοτσιφάλι, Ρωμέικο και Μοσχάτο Σπίνας, μαζί με διεθνείς ποικιλίες όπως Syrah, Cabernet, Merlot και Chardonnay. Η Pnevmatikakis διατηρεί έτσι έναν ξεκάθαρο οικογενειακό χαρακτήρα, συνδέοντας την ιστορία της Κισσάμου με τη σύγχρονη παραγωγή κρητικού κρασιού.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία της Pnevmatikakis Winery βασίζεται στη συνέχεια της κρητικής οινοποιητικής παράδοσης, χωρίς να απορρίπτει τα εργαλεία της σύγχρονης τεχνολογίας. Η οικογένεια δίνει ιδιαίτερη έμφαση στις τοπικές ποικιλίες και στην προσπάθεια να αναδεικνύονται μέσα από τις διαφορετικές συνθήκες του κρητικού αμπελώνα.",
  "Στον πυρήνα της παραγωγής βρίσκονται ποικιλίες όπως το Βιδιανό, η Βηλάνα, το Πλυτό, το Λιάτικο, το Κοτσιφάλι, το Ρωμέικο και το Μοσχάτο Σπίνας. Παράλληλα, η οικογένεια καλλιεργεί και διεθνείς ποικιλίες, εξετάζοντας τον τρόπο με τον οποίο μπορούν να εκφραστούν μέσα στο κρητικό περιβάλλον.",
  "Η προσέγγιση δεν περιορίζεται στους ιδιόκτητους αμπελώνες. Η μακροχρόνια συνεργασία με μικρούς τοπικούς παραγωγούς επιτρέπει στο οινοποιείο να αξιοποιεί σταφύλια από διαφορετικές θέσεις της Κρήτης, διατηρώντας παράλληλα τον έλεγχο της πρώτης ύλης.",
  "Στο οινοποιείο, ο σύγχρονος εξοπλισμός και το επιστημονικό προσωπικό συνδυάζονται με παραδοσιακές πρακτικές. Η πέτρινη κάβα και το Μουσείο Οίνου αποτελούν φυσική συνέχεια αυτής της φιλοσοφίας: η παράδοση δεν λειτουργεί ως αντίθεση στην εξέλιξη, αλλά ως σημείο αναφοράς. Για την Pnevmatikakis, το ζητούμενο είναι ένα κρασί που παραμένει αναγνωρίσιμα κρητικό, ενώ μπορεί να εκφράζεται μέσα από διαφορετικές ποικιλίες και σύγχρονα στυλ οινοποίησης.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "pnevmatikakis-winery" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
