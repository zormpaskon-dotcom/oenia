// Κείμενο story για τα Ελληνικά Κελλάρια Οίνων (Δ. Κουρτάκης), δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Τα Ελληνικά Κελλάρια Οίνων – Δ. Κουρτάκης αποτελούν μία από τις ιστορικότερες οικογένειες του ελληνικού κρασιού, με πορεία που ξεκινά το 1895, όταν ο Βασίλης Κουρτάκης ίδρυσε την πρώτη του εταιρεία στην Αθήνα. Το 1905 η οικογένεια ξεκίνησε την οινοπαραγωγική της δραστηριότητα στο Μαρκόπουλο Μεσογείων, περιοχή που παραμένει μέχρι σήμερα συνδεδεμένη με την έδρα και την παραγωγική της ιστορία.",
  "Η δεύτερη γενιά, με τον Δημήτρη Κουρτάκη, έβαλε τις βάσεις για τη μετάβαση από το χύμα κρασί στην εμφιάλωση και διεύρυνε σημαντικά τη διανομή των ελληνικών κρασιών. Στις επόμενες δεκαετίες η εταιρεία επένδυσε στην τεχνολογία και στην ανάπτυξη σύγχρονων οινοποιητικών εγκαταστάσεων, ενώ παράλληλα διεύρυνε τη δραστηριότητά της σε διαφορετικές ελληνικές αμπελουργικές ζώνες και ποικιλίες.",
  "Το 2000 υιοθετήθηκε η ονομασία «Ελληνικά Κελλάρια Οίνων», σηματοδοτώντας τη διευρυμένη ταυτότητα της εταιρείας. Η φιλοσοφία της βασίζεται στη συνάντηση της μακρόχρονης οικογενειακής εμπειρίας με σύγχρονες μεθόδους οινοποίησης, με στόχο την ανάδειξη του ελληνικού αμπελώνα και τη δημιουργία κρασιών με σταθερή ποιότητα και ευρύτερη παρουσία στην Ελλάδα και το εξωτερικό.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "greek-wine-cellars-kourtakis" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
