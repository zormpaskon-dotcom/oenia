// Κείμενο story + philosophy για το Idaia Winery, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στο Βενεράτο Ηρακλείου, στην καρδιά του κρητικού αμπελώνα και μέσα στη ζώνη ΠΟΠ Δαφνές, η Idaia Winery αποτελεί ένα οικογενειακό οινοποιείο με σαφή προσανατολισμό στην ανάδειξη της Κρήτης. Ιδρύθηκε από τους οινολόγους Βασίλη Λαδερό και Καλλιόπη Βολιτάκη, οι οποίοι ξεκίνησαν το εγχείρημά τους το 2000, αξιοποιώντας αρχικά τον οικογενειακό αμπελώνα στο Βενεράτο. Η πρώτη εμφιάλωση πραγματοποιήθηκε το 2002.",
  "Το ξεκίνημα ήταν ιδιαίτερα μικρό: ένας αποθηκευτικός χώρος, τρεις ανοξείδωτες δεξαμενές και πέντε δρύινα βαρέλια. Με σταδιακές επενδύσεις, συνεργασίες με αμπελουργούς της περιοχής και συνεχή δουλειά στον αμπελώνα, η Idaia εξελίχθηκε σε ένα σύγχρονο οικογενειακό οινοποιείο.",
  "Σήμερα, η δεύτερη γενιά συμμετέχει ενεργά στην επιχείρηση, μεταφέροντας τη γνώση προς την επόμενη εποχή. Η παραγωγή φτάνει περίπου τις 130.000 φιάλες ετησίως, ενώ σημαντικό μέρος των κρασιών ταξιδεύει εκτός Ελλάδας. Η ταυτότητα της Idaia παραμένει στενά δεμένη με το Βενεράτο, το Μαλεβίζι και τις ποικιλίες που χαρακτηρίζουν τον κρητικό αμπελώνα.",
].join("\n\n");

const PHILOSOPHY = [
  "Στην Idaia Winery, η οινοποίηση ξεκινά από την πεποίθηση ότι οι γηγενείς ποικιλίες είναι ο πιο άμεσος τρόπος να εκφραστεί ο χαρακτήρας της Κρήτης. Το Βιδιανό, το Θραψαθήρι, το Λιάτικο, η Βηλάνα και άλλες κρητικές ποικιλίες βρίσκονται στον πυρήνα της παραγωγής, με στόχο κάθε κρασί να διατηρεί σαφή σχέση με την προέλευση και το terroir του.",
  "Οι ιδιόκτητοι αμπελώνες της Idaia βρίσκονται σε υψόμετρο περίπου 400–500 μέτρων και καλλιεργούνται με οργανικά σκευάσματα, χωρίς λίπανση. Παράλληλα, το οινοποιείο συνεργάζεται μακροχρόνια με αμπελουργούς της περιοχής, ιδιαίτερα σε ορεινότερες θέσεις, όπου το υψόμετρο συμβάλλει στη διατήρηση της οξύτητας. Η εργασία στον αμπελώνα γίνεται χειρωνακτικά και προσαρμόζεται στις ανάγκες κάθε χρονιάς.",
  "Στο οινοποιείο εφαρμόζεται μια ήπια προσέγγιση, με όσο το δυνατόν λιγότερες παρεμβάσεις. Η ομάδα παρακολουθεί συνεχώς την εξέλιξη των κρασιών και προσαρμόζει τις αποφάσεις στις ιδιαιτερότητες κάθε τρύγου. Η χρήση της βαρύτητας για τη μεταφορά του κρασιού και η υπόγεια κάβα παλαίωσης εντάσσονται σε αυτή τη λογική.",
  "Για την Idaia, η ποιότητα συνδέεται τελικά με την αυθεντικότητα: κρασιά που εκφράζουν την ποικιλία, τον τόπο και τη χρονιά τους, ενώ παράλληλα σέβονται το περιβάλλον και την κρητική οινοποιητική παράδοση.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "idaia-winery" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
