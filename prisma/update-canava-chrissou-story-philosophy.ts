// Κείμενο story + philosophy για το Canava Chrissou – Tselepos, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Η Canava Chrissou – Tselepos γεννήθηκε στη Σαντορίνη μέσα από τη συνεργασία του οινοποιού Γιάννη Τσέλεπου, ιδρυτή του Κτήματος Τσέλεπου στην Αρκαδία, με την οικογένεια Χρυσού, μια οικογένεια με βαθιές ρίζες στον σαντορινιό αμπελώνα.",
  "Το εγχείρημα ξεκίνησε το 2013, με κοινό στόχο την αναβίωση της παλιάς οικογενειακής Κάναβας και την αξιοποίηση των ιδιόκτητων αμπελώνων της οικογένειας, συνολικής έκτασης περίπου 12 εκταρίων, στον Πύργο, το Εμπορείο και το Μεγαλοχώρι. Μετά τον τρύγο του 2013 ξεκίνησε ένα μακροχρόνιο πρόγραμμα αναζωογόνησης του πολυετούς αμπελώνα, με παραδοσιακές καλλιεργητικές πρακτικές και στόχο τη σταδιακή βελτίωση της παραγωγικής του ισορροπίας.",
  "Στο επίκεντρο βρίσκεται το Ασύρτικο, η χαρακτηριστική ποικιλία της Σαντορίνης. Οι αμπελώνες, με ηλικίες που φτάνουν πολλές δεκαετίες, βρίσκονται σε ηφαιστειογενή εδάφη πλούσια σε ελαφρόπετρα και τέφρα και καλλιεργούνται με την παραδοσιακή διαμόρφωση της κουλούρας.",
  "Από αυτή τη συνάντηση παράγονται κρασιά που εξερευνούν διαφορετικές εκφράσεις του σαντορινιού Ασύρτικου, από τη σύγχρονη Santorini έως το Νυχτέρι και τις παλαιότερες αμπελουργικές επιλογές του κτήματος.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία της Canava Chrissou – Tselepos ξεκινά από μια απλή αρχή: η ποιότητα του κρασιού καθορίζεται πρώτα στον αμπελώνα. Για αυτό η προσπάθεια επικεντρώνεται στη διατήρηση και αναζωογόνηση των παλιών αμπελιών και στην όσο το δυνατόν καλύτερη αξιοποίηση των ιδιαίτερων συνθηκών της Σαντορίνης.",
  "Το Ασύρτικο βρίσκεται στο επίκεντρο. Ηφαιστειογενή εδάφη, ξηρό κλίμα, δυνατοί άνεμοι και παλιά αυτόρριζα αμπέλια δημιουργούν ένα ιδιαίτερο περιβάλλον, μέσα στο οποίο η ποικιλία αποκτά υψηλή οξύτητα, συμπύκνωση και έντονη ορυκτότητα.",
  "Η οινοποίηση ακολουθεί διαφορετικές διαδρομές ανάλογα με την έκφραση που επιδιώκεται. Η βασική Santorini ζυμώνει σε ανοξείδωτες δεξαμενές και παραμένει περίπου τρεις μήνες στις λεπτές οινολάσπες, ενώ το Νυχτέρι ακολουθεί πιο παραδοσιακή και μακρά προσέγγιση, με ζύμωση και παλαίωση σε μεγάλα γαλλικά δρύινα βαρέλια.",
  "Στόχος είναι η σύγχρονη οινοποίηση να λειτουργεί ως εργαλείο για την ανάδειξη του αμπελώνα και όχι για να καλύπτει τον χαρακτήρα του, διατηρώντας στο επίκεντρο την ποικιλία, το terroir και τη δυνατότητα παλαίωσης του σαντορινιού Ασύρτικου.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "canava-chrissou-tselepos" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
