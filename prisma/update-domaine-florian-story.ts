// Κείμενο story για το Domaine Florian, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στην Επανομή, λίγο έξω από τη Θεσσαλονίκη, το Domaine Florian είναι ένα μικρό οικογενειακό οινοποιείο που ξεκίνησε τη διαδρομή του το 2008, με επίκεντρο την ποιότητα και τη στενή σχέση ανάμεσα στον αμπελώνα και το κρασί.",
  "Οι αμπελώνες βρίσκονται στους ήπιους λόφους της Επανομής, σε ένα ιδιαίτερο μικροκλίμα που διαμορφώνεται από την εγγύτητα στη θάλασσα, τους σταθερούς ανέμους και τα αμμώδη-αργιλώδη εδάφη της περιοχής. Το περιβάλλον αυτό προσφέρει ιδιαίτερα καλές συνθήκες για την καλλιέργεια λευκών ποικιλιών, ενώ το οινοποιείο καλλιεργεί διαφορετικές ελληνικές και διεθνείς ποικιλίες.",
  "Η φιλοσοφία του Domaine Florian συνοψίζεται στην αρχή «quality over quantity»: προσεκτική και όσο γίνεται βιώσιμη διαχείριση του αμπελώνα, αξιοποίηση των υπολειμμάτων της οινοποίησης και ελαιοπαραγωγής για φυσική λίπανση και παρεμβάσεις που αφήνουν κάθε σοδειά να εκφράσει τον χαρακτήρα του αμπελιού και της ποικιλίας.",
  "Σήμερα, το οινοποιείο συνδυάζει την παραγωγή κρασιού με τη φιλοξενία, μέσα από γευσιγνωσίες και εμπειρίες γύρω από το κρασί και την τοπική γαστρονομία.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "domaine-florian" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
