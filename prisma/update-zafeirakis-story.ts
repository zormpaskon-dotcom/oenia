// Κείμενο story για το Κτήμα Ζαφειράκη, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στον Τύρναβο Θεσσαλίας, στη ζώνη ΠΓΕ Τύρναβος, το Κτήμα Ζαφειράκη συνεχίζει μια οικογενειακή παράδοση αμπελουργίας που ξεπερνά τον έναν αιώνα. Σήμερα, την τέταρτη γενιά εκπροσωπεί ο Χρήστος Ζαφειράκης, οινολόγος με σπουδές στην Ελλάδα και την Ιταλία, ο οποίος επέστρεψε στον Τύρναβο το 2005 και φύτεψε τον πρώτο βιολογικό αμπελώνα του κτήματος.",
  "Οι αμπελώνες εκτείνονται σε περισσότερα από 12 εκτάρια, κυρίως στις περιοχές Παλαιόμυλος και Καμπιλάγας, με διαφορετικά εδαφικά χαρακτηριστικά που συμβάλλουν στη διαφοροποίηση των κρασιών. Η καλλιέργεια ακολουθεί οργανικές πρακτικές, ενώ από το 2019 εφαρμόζονται και βιοδυναμικές πρακτικές, με έμφαση στην ελάχιστη παρέμβαση και στη διατήρηση της βιοποικιλότητας.",
  "Στο επίκεντρο βρίσκεται η Λημνιώνα, μια γηγενής ποικιλία που ο Χρήστος Ζαφειράκης συνέβαλε σημαντικά στην αναβίωσή της και στην ανάδειξή της μέσα από σύγχρονες, κομψές εκφράσεις. Παράλληλα, το κτήμα καλλιεργεί Μαλαγουζιά, Chardonnay, Ασύρτικο και Syrah.",
  "Η φιλοσοφία του Κτήματος συνοψίζεται στην «Αγάπη, Γνώση και Σεβασμό στην Παράδοση», με στόχο κάθε κρασί να μεταφέρει όσο το δυνατόν πιο καθαρά την έκφραση του αμπελώνα και του Τυρνάβου.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "domaine-zafeirakis" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
