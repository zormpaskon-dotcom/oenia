// Κείμενο story + philosophy για το Patoinos (Terre de l'Apocalypse), δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στην Πάτμο, ένα νησί με παλιά αλλά σχεδόν ξεχασμένη αμπελουργική παράδοση, το Patoinos δημιουργήθηκε με στόχο να επαναφέρει το αμπέλι στο τοπίο και στην καθημερινότητα του νησιού. Ιστορικές πηγές και παλιές αναβαθμίδες μαρτυρούν ότι η Πάτμος υπήρξε κάποτε σημαντικός τόπος παραγωγής κρασιού, με την τοπική παραγωγή να φτάνει μέχρι την Αίγυπτο. Με την πάροδο του χρόνου, όμως, η αμπελουργία σχεδόν εξαφανίστηκε.",
  "Το Patoinos ξεκίνησε ως προσπάθεια ανασύστασης αυτού του αμπελώνα. Δημιουργήθηκε ένας νέος αμπελώνας δύο εκταρίων στην περιοχή Πέτρα, ενώ το οινοποιείο βρίσκεται στη Βαγιά, στο βόρειο τμήμα του νησιού. Το πρώτο κρασί με την υπογραφή Patoinos κυκλοφόρησε το 2016, από δύο ελληνικές νησιωτικές ποικιλίες: Ασύρτικο και Μαυροθήρικο.",
  "Πίσω από το εγχείρημα βρίσκεται ο Josef Zisyadis, με τη συμβολή Ελλήνων και Ελβετών αμπελουργών και οινολόγων. Σήμερα το Patoinos λειτουργεί ως ένα μικρό αγρο-οικολογικό domaine που συνδυάζει αμπελώνα, οινοποιείο, ελαιώνα, χώρο γευσιγνωσίας και δράσεις γύρω από την αγροτική παράδοση της Πάτμου.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία του Patoinos βασίζεται στην ιδέα ότι η αναβίωση ενός αμπελώνα δεν αφορά μόνο την παραγωγή κρασιού, αλλά ολόκληρο το αγροτικό οικοσύστημα του τόπου. Το εγχείρημα ακολουθεί βιοδυναμική και αγρο-οικολογική προσέγγιση, με περιορισμένη μηχανοποίηση και έμφαση στη διατήρηση ενός ζωντανού εδάφους και ενός βιώσιμου αμπελουργικού περιβάλλοντος.",
  "Ο αμπελώνας έχει έκταση δύο εκταρίων και αποτελείται κατά περίπου δύο τρίτα από λευκές και ένα τρίτο από ερυθρές ποικιλίες. Στο επίκεντρο βρίσκονται ελληνικές, νησιωτικές ποικιλίες, με το Ασύρτικο να αποτελεί βασικό άξονα και το Μαυροθήρικο να συμπληρώνει τον ερυθρό χαρακτήρα του αμπελώνα. Στόχος είναι η παραγωγή κρασιών με σαφή περιφερειακό χαρακτήρα, μέσα από ποικιλίες που συνδέονται με το ελληνικό αμπελουργικό παρελθόν.",
  "Η ίδια λογική επεκτείνεται πέρα από το κρασί. Το Patoinos διατηρεί τράπεζα τοπικών σπόρων, ελαιώνα και ελαιοτριβείο, ενώ οργανώνει επισκέψεις και εκπαιδευτικές δράσεις για την αγροτική ζωή, την κομποστοποίηση και τη γνώση γύρω από τη γη.",
  "Έτσι, το κρασί λειτουργεί ως μέρος ενός ευρύτερου εγχειρήματος: να ξανασυνδεθεί η Πάτμος με την αμπελουργία, τη γεωργία και τις τοπικές της παραδόσεις.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "patoinos-winery" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
