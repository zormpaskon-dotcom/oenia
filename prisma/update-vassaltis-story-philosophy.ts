// (χωρίς τα inline citation links του αρχικού κειμένου, όπως ζητήθηκε).
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στη Σαντορίνη, η Vassaltis Vineyards δημιουργήθηκε από την επιστροφή του Γιάννη Βαλαμβούς στην Ελλάδα και την απόφασή του να δώσει νέα ζωή στους οικογενειακούς αμπελώνες που είχε κληρονομήσει από τον πατέρα του. Η αρχή έγινε μέσα στην οικονομική κρίση του 2010, όταν η επιστροφή του από το Λονδίνο οδήγησε σε ένα νέο εγχείρημα γύρω από το κρασί και τον σαντορινιό αμπελώνα.",
  "Ο αρχικός αμπελώνας αποτελούνταν από περίπου τέσσερα εκτάρια. Ο Βαλαμβούς δημιούργησε μια ομάδα με τον οινολόγο Ηλία Ρουσσάκη και στη συνέχεια τον Γιάννη Παπαικονόμου, με κοινό στόχο την ανάδειξη της ποιότητας των κρασιών της Σαντορίνης και τη σύγχρονη παρουσία τους στο διεθνές κοινό.",
  "Το 2014 γεννήθηκε επίσημα η Vassaltis και παράλληλα δημιουργήθηκε ένα σύγχρονο boutique οινοποιείο, σχεδιασμένο με μινιμαλιστική αισθητική και άμεση σχέση με το τοπίο. Η αρχιτεκτονική του συνδυάζει καθαρές γραμμές, τοπική μαύρη ηφαιστειακή πέτρα και μεγάλες επιφάνειες που ανοίγουν προς τη θάλασσα και τους αμπελώνες. Σήμερα, το Ασύρτικο αποτελεί βασικό άξονα της παραγωγής, ενώ η Vassaltis εξερευνά και άλλες γηγενείς ποικιλίες της Σαντορίνης μέσα από διαφορετικές οινοποιητικές εκφράσεις.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία της Vassaltis βασίζεται σε μια ιδέα που η ίδια η ομάδα περιγράφει ως «παραδοσιακή αλλά βιώσιμη εξέλιξη». Η παράδοση της Σαντορίνης αποτελεί αφετηρία, όχι τελικό προορισμό: στόχος είναι να διατηρηθούν οι γνώσεις του παρελθόντος και ταυτόχρονα να εξελιχθούν μέσα από σύγχρονες πρακτικές.",
  "Στο επίκεντρο βρίσκεται η καθαρή έκφραση του terroir. Το Ασύρτικο, μαζί με το Αηδάνι, το Αθύρι, τη Μανδηλαριά και το Μαυροτράγανο, εκφράζει τον ηφαιστειακό χαρακτήρα του νησιού μέσα από διαφορετικές οινοποιήσεις. Πολλά από τα αμπέλια της Vassaltis είναι ηλικίας άνω των 60 ετών, ενώ η παραδοσιακή κουλούρα παραμένει βασικό στοιχείο της αμπελουργίας της Σαντορίνης.",
  "Η ομάδα δεν αντιμετωπίζει την παράδοση ως σύνολο απαράβατων κανόνων. Πειραματίζεται με διαφορετικές τεχνικές στον αμπελώνα και στο οινοποιείο, όπως trellising σε επιλεγμένα αμπέλια, πολύ πρωινό τρύγο, battonage, ωρίμαση σε δρύινα δοχεία και ελεγχόμενη οξείδωση. Η επιλογή κάθε τεχνικής γίνεται με στόχο την έκφραση της πρώτης ύλης και όχι την επιβολή ενός συγκεκριμένου στυλ.",
  "Παράλληλα, η βιωσιμότητα αποτελεί μέρος της ευρύτερης φιλοσοφίας, τόσο περιβαλλοντικά όσο και στον τρόπο με τον οποίο αντιμετωπίζονται οι άνθρωποι και οι συνεργάτες του οινοποιείου. Για τη Vassaltis, η εξέλιξη έχει αξία όταν παραμένει συνδεδεμένη με τον τόπο.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "vassaltis-vineyards" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
