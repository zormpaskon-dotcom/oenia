// Κείμενο story για το Vriniotis Winery, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στα Γιάλτρα της Βόρειας Εύβοιας, κοντά στην Αιδηψό, το Vriniotis Winery αποτελεί μια οικογενειακή οινοποιία με βαθιές ρίζες στην αμπελουργική παράδοση της περιοχής. Η σχέση της οικογένειας Βρυνιώτη με το αμπέλι ξεκινά από προηγούμενες γενιές, όταν δημιουργήθηκε το παλιό πέτρινο πατητήρι-οινοποιείο, δίπλα στο οποίο βρίσκεται σήμερα η σύγχρονη οινοποιητική μονάδα.",
  "Ο ιδιόκτητος αμπελώνας εκτείνεται σε περίπου 100 στρέμματα, στους πρόποδες του Τελέθριου, σε υψόμετρο 200–450 μέτρων. Εκεί καλλιεργούνται γηγενείς ποικιλίες της Βόρειας Εύβοιας, όπως το Βραδυανό και η Μαυροκουντούρα, μαζί με Ασύρτικο, Μαλαγουζιά, Αηδάνι και Μονεμβασιά, αλλά και Syrah.",
  "Ιδιαίτερη θέση έχει το Βραδυανό, μια παλιά ευβοιώτικη ποικιλία που η οικογένεια συνέβαλε στην αναβίωσή της. Το οινοποιείο συνδυάζει την παραδοσιακή κληρονομιά με τη σύγχρονη τεχνολογία, διατηρώντας παράλληλα τον χαρακτήρα του τόπου και των ποικιλιών.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "vriniotis-winery" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
