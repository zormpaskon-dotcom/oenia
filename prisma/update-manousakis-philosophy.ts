// Κείμενο philosophy για το Manousakis Winery, δόθηκε αυτούσιο από τον χρήστη.
// Το υπάρχον story (Ted Manousakis, Alexandra 2007) παραμένει άθικτο — αυτό το
// κείμενο συμπληρώνει το κενό πεδίο philosophy με τεχνικές λεπτομέρειες
// αμπελώνα/ποικιλιών που δεν καλύπτονταν εκεί.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const PHILOSOPHY = [
  "Από την αρχή, η επιλογή των ποικιλιών έγινε με βάση τις συνθήκες του τόπου. Με τη συμβολή ειδικών συμβούλων, επιλέχθηκαν κυρίως μεσογειακές ποικιλίες του Ροδανού, όπως Syrah, Grenache, Mourvèdre και Roussanne, οι οποίες καλλιεργούνται μέχρι σήμερα. Οι αμπελώνες εκτείνονται σε περίπου 13 εκτάρια, σε υψόμετρο 350–650 μέτρων, σε λοφώδη εδάφη με σημαντική παρουσία αργίλου.",
  "Η καλλιέργεια είναι οργανική και βασίζεται σε χειρωνακτική φροντίδα, με διαφορετική διαχείριση των μικρών αμπελοτεμαχίων ανάλογα με τις εδαφικές τους συνθήκες. Το αποτέλεσμα είναι μια προσέγγιση που συνδέει το κρητικό τοπίο με ένα διεθνές οινοποιητικό ύφος, ενώ η φιλοξενία, οι γευσιγνωσίες και η κρητική κουζίνα αποτελούν πλέον αναπόσπαστο μέρος της εμπειρίας του οινοποιείου.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "manousakis-winery" },
    data: { philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: philosophy ενημερώθηκε (${PHILOSOPHY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
