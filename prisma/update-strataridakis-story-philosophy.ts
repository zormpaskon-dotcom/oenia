// Κείμενο story + philosophy για το Strataridakis Winery, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στα Καστελλιανά Ηρακλείου, στους πρόποδες των Αστερουσίων, η οικογένεια Στραταριδάκη συνεχίζει μια αμπελουργική παράδοση που ξεκινά περίπου το 1900. Ο Κωνσταντίνος Στραταριδάκης ήταν ο πρώτος της οικογένειας που ασχολήθηκε συστηματικά με τα αμπέλια στις Αρχάνες. Η επόμενη γενιά, ο Αριστείδης, απέκτησε το 1954 μια μεγάλη έκταση στα Καστελλιανά, όπου υπήρχαν μεταξύ άλλων παλαιά μοναστηριακά κλήματα της Σιναϊτικής Μονής των Αγίων Αποστόλων.",
  "Με τα χρόνια, η οικογένεια δημιούργησε ένα ενιαίο κτήμα περίπου 50 εκταρίων, από τα οποία 25 εκτάρια αποτελούν αμπελώνα. Το σύγχρονο οινοποιείο κατασκευάστηκε μεταξύ 2006 και 2007 και σηματοδότησε τη μετάβαση από την αμπελουργική παραγωγή στην πλήρη οικογενειακή οινοποίηση.",
  "Οι αμπελώνες βρίσκονται σε διαφορετικά υψόμετρα, από περίπου 180 έως 500 μέτρα, με ποικίλες κλίσεις και εδάφη. Η παραγωγή περιλαμβάνει γηγενείς κρητικές ποικιλίες όπως Βιδιανό, Βηλάνα, Θραψαθήρι, Ασύρτικο, Λιάτικο και Κοτσιφάλι, αλλά και διεθνείς ποικιλίες όπως Chardonnay, Cabernet, Merlot και Syrah. Σήμερα, το οινοποιείο αποτελεί συνέχεια τριών γενεών αμπελουργών και ένα από τα πιο νότια οινοποιεία της Ευρώπης.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία του Οινοποιείου Στραταριδάκη βασίζεται στην ισορροπία ανάμεσα στην παράδοση και την καινοτομία. Στόχος είναι τα κρασιά να παραμένουν άμεσα συνδεδεμένα με το terroir των Καστελλιανών, ενώ η σύγχρονη τεχνολογία χρησιμοποιείται για να προστατεύσει την ποιότητα της πρώτης ύλης και να αναδείξει τα χαρακτηριστικά κάθε ποικιλίας.",
  "Ο αμπελώνας είναι χωρισμένος σε επιμέρους τμήματα, καθώς οι διαφορετικές θέσεις παρουσιάζουν διαφορετικά εδάφη, υψόμετρα και μικροκλιματικές συνθήκες. Η οικογένεια προσαρμόζει την επιλογή των ποικιλιών σε αυτά τα χαρακτηριστικά, καλλιεργώντας τόσο γηγενείς κρητικές ποικιλίες όσο και διεθνείς.",
  "Οι αποδόσεις ελέγχονται μέσω κλαδέματος και επιλογής, ενώ ο τρύγος γίνεται χειρωνακτικά και με αυστηρή διαλογή, ώστε στο οινοποιείο να φτάνουν υγιή και πλήρως ώριμα σταφύλια. Η μεταφορά πραγματοποιείται σε μικρά τελάρα και η οινοποίηση ξεκινά μέσα σε λίγες ώρες από τη συγκομιδή.",
  "Στο οινοποιείο, σύγχρονες ανοξείδωτες δεξαμενές ελεγχόμενης θερμοκρασίας συνυπάρχουν με γαλλικά και αμερικανικά δρύινα βαρέλια για την παλαίωση επιλεγμένων κρασιών. Η τεχνολογία λειτουργεί έτσι ως εργαλείο ακρίβειας, χωρίς να απομακρύνει το κρασί από την προέλευση και την ποικιλία του. Η βασική ιδέα παραμένει σταθερή: ο τόπος πρώτα, η τεχνική στη συνέχεια.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "strataridakis-winery" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
