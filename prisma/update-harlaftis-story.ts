// Κείμενο story για το Château Harlaftis, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στη Σταμάτα Αττικής, στις βόρειες πλαγιές της Πεντέλης, η ιστορία της Οινοποιίας Χαρλαύτη ξεκινά το 1934, όταν ο Νίκος Αθανασιάδης δημιουργεί τον πρώτο οικογενειακό αμπελώνα και ένα πέτρινο οινοποιείο με υπόγειους χώρους παλαίωσης. Ήδη από το 1938, οι πρώτες ετικέτες της οικογένειας εμφιαλώνονται και φτάνουν σε μερικά από τα σημαντικότερα ξενοδοχεία και σημεία της Αθήνας.",
  "Στις επόμενες δεκαετίες, η οικογένεια επεκτείνει τον αμπελώνα και ανανεώνει τις ποικιλίες της, ενώ το 1997 κάνει ένα σημαντικό βήμα προς τη Νεμέα, αποκτώντας αμπελώνες στην Αχλαδιά και στο Κούτσι και δημιουργώντας εκεί νέο οινοποιείο. Σήμερα, η τρίτη γενιά συνεχίζει την οικογενειακή διαδρομή, συνδυάζοντας την παράδοση με τη σύγχρονη οινολογική τεχνογνωσία.",
  "Από το Αγιωργίτικο της Νεμέας έως το Ασύρτικο, τη Chardonnay και τη Malagouzia, η Χαρλαύτη δουλεύει με διαφορετικά terroirs και ποικιλίες, διατηρώντας ως σταθερή αρχή την οικογενειακή φροντίδα σε κάθε στάδιο, από τον αμπελώνα μέχρι την εμφιάλωση.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "harlaftis-estate" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
