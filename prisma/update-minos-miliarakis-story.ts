// Κείμενο story για το Μινώς Μηλιαράκης, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στα Πεζά Ηρακλείου, στο κέντρο μιας από τις σημαντικότερες αμπελουργικές περιοχές της Κρήτης, το Οινοποιείο Μηλιαράκη – ΜΙΝΩΣ αποτελεί ένα από τα ιστορικότερα ονόματα του κρητικού κρασιού. Η ιστορία της οικογένειας ξεκινά στα τέλη του 19ου αιώνα, όταν ο Αντωνάκης Μηλιαράκης εγκαταστάθηκε στα Πεζά και δημιούργησε ένα χάνι, όπου προσέφερε στους ταξιδιώτες φαγητό και το δικό του κρασί.",
  "Το 1932, τέσσερα από τα παιδιά του ίδρυσαν τη ΜΙΝΩΣ, μετατρέποντας την οικογενειακή παράδοση σε οργανωμένη οινοποιητική επιχείρηση. Το 1952 πραγματοποιήθηκε η πρώτη επιτυχημένη εμφιάλωση κρασιού στην Κρήτη από τη ΜΙΝΩΣ, ενώ λίγα χρόνια αργότερα τα εμφιαλωμένα κρασιά της άρχισαν να ταξιδεύουν και στο εξωτερικό. Η εταιρεία συνέβαλε παράλληλα στην ανάδειξη της αμπελουργικής ζώνης των Πεζών και των χαρακτηριστικών κρητικών ποικιλιών της.",
  "Σήμερα, η ΜΙΝΩΣ συνεχίζει να επικεντρώνεται στο εμφιαλωμένο ποιοτικό κρασί και στην ανάδειξη του κρητικού αμπελώνα. Στο portfolio βρίσκονται γηγενείς ποικιλίες όπως Βηλάνα, Κοτσιφάλι, Μαντηλάρι και Μαλαβαζία, ενώ η παράδοση συνδυάζεται με σύγχρονες πρακτικές οινοποίησης και παλαίωσης.",
  "Η φιλοσοφία του οινοποιείου βασίζεται στη διαρκή εξέλιξη, χωρίς να χάνεται η σύνδεση με την ιστορία, τις ποικιλίες και τον τόπο της Κρήτης.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "minos-miliarakis" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
