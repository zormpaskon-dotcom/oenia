// Κείμενο story για το Kokotos Estate, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στη Σταμάτα Αττικής, στις βόρειες πλαγιές της Πεντέλης, το Κτήμα Κοκοτού αποτελεί μια οικογενειακή οινοποιητική ιστορία που ξεκίνησε στα τέλη της δεκαετίας του 1970, όταν ο Γιώργος και η Anne Κοκοτού εγκατέλειψαν τη ζωή της πόλης για να δημιουργήσουν έναν νέο τρόπο ζωής πιο κοντά στη φύση. Το 1980 φύτεψαν τα πρώτα αμπέλια, δημιουργώντας σταδιακά έναν πρότυπο αμπελώνα σε ένα ιδιαίτερο αττικό τοπίο.",
  "Στους βιολογικούς αμπελώνες του κτήματος καλλιεργούνται ελληνικές και διεθνείς ποικιλίες, με το Σαββατιανό και το Ασύρτικο να συνυπάρχουν με Chardonnay, Cabernet Sauvignon, Merlot και Gewürztraminer. Παράλληλα, το Κτήμα συνεργάζεται με επιλεγμένους αμπελουργούς για Ροδίτη και Αγιωργίτικο.",
  "Η φιλοσοφία του βασίζεται στη φροντίδα της γης και στην προσπάθεια κάθε ποικιλία να εκφράζει με καθαρότητα τον χαρακτήρα της. Το οινοποιείο αποτελεί σήμερα έναν ολοκληρωμένο οινικό προορισμό, με αμπελώνα, χώρο γευσιγνωσίας και φιλοξενία, διατηρώντας τον οικογενειακό χαρακτήρα που βρίσκεται στον πυρήνα του από την πρώτη ημέρα.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "kokotos-estate" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
