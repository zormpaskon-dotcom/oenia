// Κείμενο story για το Κτήμα Δαλαμάρα, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στη Νάουσα, στους ανατολικούς πρόποδες του Βερμίου, το Οινοποιείο Δαλαμάρα συνεχίζει μια οικογενειακή οινική παράδοση που ξεκινά το 1840, όταν ο Ιωάννης Γεωργίου Δαλαμάρας δημιούργησε τον πρώτο οικογενειακό αμπελώνα στην περιοχή. Σήμερα, την έκτη γενιά εκπροσωπεί ο Κωστής Δαλαμάρας, ο οποίος μετά τις σπουδές του στη Γαλλία επέστρεψε στη Νάουσα και ανέλαβε την εξέλιξη του κτήματος, διατηρώντας παράλληλα τον οικογενειακό χαρακτήρα του.",
  "Οι αμπελώνες του κτήματος βρίσκονται κυρίως στις περιοχές Παλιοκαλιάς και Βαδός, σε υψόμετρο περίπου 250–350 μέτρων, με ασβεστολιθικά και αργιλώδη εδάφη. Το Ξινόμαυρο αποτελεί την καρδιά του αμπελώνα και της οινοποιητικής ταυτότητας του κτήματος, πλαισιωμένο από άλλες ελληνικές και διεθνείς ποικιλίες.",
  "Από το 1996 οι αμπελώνες καλλιεργούνται βιολογικά, ενώ η προσέγγιση στο οινοποιείο χαρακτηρίζεται από ελάχιστη παρέμβαση, με έμφαση στην πρώτη ύλη και στην έκφραση του τόπου. Η φιλοσοφία του Δαλαμάρα είναι να αφήνει το αμπέλι και το κρασί να εκφράζονται με όσο το δυνατόν μεγαλύτερη καθαρότητα, δημιουργώντας οίνους με έντονη σχέση με τη Νάουσα και το Ξινόμαυρό της.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "dalamaras" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
