// Κείμενο story + philosophy για το Kitrvs Winery, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στην Πύδνα Πιερίας, σε έναν τόπο με μακραίωνη ιστορία και άμεση σχέση με τη θάλασσα, δημιουργήθηκε το Kitrvs, ένα οινοποιητικό εγχείρημα που ξεκίνησε από την ανάγκη να εκφραστούν μέσα από το κρασί συγκεκριμένες ιδέες, επιλογές και προσωπικές αναζητήσεις. Η πρώτη μικρή σοδειά και η πρώτη οινοποίηση πραγματοποιήθηκαν το 2011, σηματοδοτώντας την αρχή ενός διαφορετικού δρόμου για την οικογένεια Γαρυπίδη.",
  "Ο αμπελώνας και το οινοποιείο βρίσκονται στην περιοχή της αρχαίας Πύδνας, σε ένα τοπίο όπου η ιστορία της Μακεδονίας συναντά τη σύγχρονη οινοπαραγωγή. Η οικογένεια επέλεξε να δημιουργήσει από την αρχή τόσο τον αμπελώνα όσο και τις εγκαταστάσεις, χωρίς να βασιστεί σε μια παλαιότερη οινοποιητική παράδοση.",
  "Στον αμπελώνα καλλιεργούνται Μαλαγουζιά, Verdicchio, Syrah και Aglianico, με επιλογές που δείχνουν τη διάθεση του Kitrvs να εξερευνήσει διαφορετικές ποικιλίες μέσα στο περιβάλλον της Πιερίας. Το αποτέλεσμα είναι μια μικρή, προσωπική παραγωγή που συνδέει τον βόρειο ελληνικό τόπο με μια σύγχρονη και πειραματική αντίληψη για το κρασί.",
].join("\n\n");

const PHILOSOPHY = [
  "Στο Kitrvs, η φιλοσοφία ξεκινά από μια απλή αλλά απαιτητική ιδέα: το κρασί πρέπει να αποτελεί αυθεντική έκφραση των ανθρώπων που το δημιουργούν, του τόπου όπου γεννιέται και των επιλογών που γίνονται στον αμπελώνα και στο οινοποιείο. Η ομάδα αντιμετωπίζει κάθε φιάλη ως ευθύνη απέναντι στον άνθρωπο που θα τη μοιραστεί στο τραπέζι.",
  "Η επιλογή των ποικιλιών αποτελεί σημαντικό μέρος αυτής της προσέγγισης. Δίπλα στη Μαλαγουζιά, το Kitrvs καλλιεργεί Syrah, Aglianico και Verdicchio, αναζητώντας τον τρόπο με τον οποίο διαφορετικές ποικιλίες μπορούν να εκφράσουν τον χαρακτήρα της βόρειας Ελλάδας. Το Syrah, για παράδειγμα, επιλέχθηκε όχι για να αντιγραφεί κάποιο συγκεκριμένο διεθνές πρότυπο, αλλά για να αποκτήσει τη δική του έκφραση μέσα στο περιβάλλον της Πιερίας.",
  "Στον αμπελώνα εφαρμόζονται πρακτικές ολοκληρωμένης διαχείρισης, με παρακολούθηση της ωρίμανσης και έλεγχο των αποδόσεων. Σε συγκεκριμένα κρασιά χρησιμοποιούνται επίσης γηγενείς ζύμες και διαφορετικές μέθοδοι οινοποίησης, όπως η ζύμωση σε τσιμεντένιες δεξαμενές, ανάλογα με τον χαρακτήρα κάθε ποικιλίας.",
  "Για το Kitrvs, η παράδοση και η τεχνολογία δεν είναι αντίθετες έννοιες. Η καινοτομία λειτουργεί ως εργαλείο για να εξερευνηθεί βαθύτερα ο τόπος και να δημιουργηθούν κρασιά με προσωπικότητα, ακρίβεια και δικό τους χαρακτήρα.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "kitrvs" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
