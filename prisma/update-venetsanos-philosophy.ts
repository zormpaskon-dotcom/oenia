// (χωρίς τα inline citation links του αρχικού κειμένου, όπως ζητήθηκε).
// Το υπάρχον story παραμένει άθικτο — καλύπτει ήδη τα ίδια βασικά γεγονότα.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const PHILOSOPHY = [
  "Η φιλοσοφία της Venetsanos Winery βασίζεται στη συνέχεια μιας οικογενειακής οινοποιητικής παράδοσης μέσα σε έναν χώρο που αποτελεί από μόνος του μέρος της ιστορίας του σαντορινιού κρασιού. Η αξιοποίηση της βαρύτητας, που αποτέλεσε βασική αρχή στον αρχικό σχεδιασμό του οινοποιείου, παραμένει χαρακτηριστικό παράδειγμα του τρόπου με τον οποίο η οικογένεια προσάρμοσε την παραγωγή στις φυσικές συνθήκες του νησιού.",
  "Η σύγχρονη λειτουργία συνδυάζει αυτή την ιστορική υποδομή με νέες τεχνικές οινοποίησης. Τα κρασιά της Venetsanos παραμένουν συνδεδεμένα με τις βασικές ποικιλίες και τα χαρακτηριστικά του σαντορινιού αμπελώνα, ενώ η παραγωγή περιλαμβάνει διαφορετικές εκφράσεις του Ασύρτικου, του Νυκτεριού και του Vinsanto.",
  "Ιδιαίτερη θέση έχει το Vinsanto, ένα γλυκό κρασί που παράγεται από σταφύλια τα οποία αφήνονται να λιαστούν φυσικά στον ήλιο πριν από την οινοποίηση. Η συγκεκριμένη πρακτική αποτελεί μέρος της μακράς παράδοσης των γλυκών κρασιών της Σαντορίνης.",
  "Παράλληλα, η ίδια η σχέση του οινοποιείου με το τοπίο αποτελεί σημαντικό μέρος της ταυτότητάς του. Το κτίριο είναι κυριολεκτικά ενσωματωμένο στην πλαγιά πάνω από την Καλντέρα, δημιουργώντας έναν χώρο όπου η παραγωγή, η αρχιτεκτονική και ο αμπελώνας συνυπάρχουν. Η Venetsanos συνεχίζει έτσι να εξελίσσει την παραγωγή της χωρίς να αποκόπτεται από την ιστορική υποδομή και τη φυσική γεωγραφία της Σαντορίνης.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "venetsanos-winery" },
    data: { philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: philosophy ενημερώθηκε`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
