// Κείμενο story για το Kontozisis Organic Vineyards, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στην Καρδίτσα, στη Θεσσαλία, η ιστορία του Κτήματος Κοντοζήση ξεκίνησε το 1991, όταν η οικογένεια δημιούργησε μια ταβέρνα και, παράλληλα, ο Γιώργος Κοντοζήσης άρχισε να καλλιεργεί αμπέλια με τους δύο γιους του. Ο πρώτος αμπελώνας, φυτεμένος με Ροδίτη, προοριζόταν αρχικά να καλύψει τις ανάγκες της οικογενειακής ταβέρνας. Σταδιακά, όμως, η αμπελουργική δραστηριότητα εξελίχθηκε σε ένα ολοκληρωμένο οινοποιητικό εγχείρημα.",
  "Οι πρώτες οινοποιήσεις πραγματοποιούνταν σε δεξαμενές στην αυλή του οικογενειακού σπιτιού, ενώ το οργανωμένο οινοποιείο άρχισε να δημιουργείται μετά το 2000 και ολοκληρώθηκε το 2008. Σήμερα οι αμπελώνες της οικογένειας εκτείνονται σε περίπου 140 στρέμματα, με την καλλιέργεια και την οινοποίηση να παραμένουν στενά συνδεδεμένες με την οικογενειακή εργασία.",
  "Ιδιαίτερη θέση στην ταυτότητα του Κτήματος έχει η βιολογική αμπελουργία και η αναβίωση της Λημνιώνας, μιας σημαντικής θεσσαλικής ποικιλίας. Η φιλοσοφία του Κοντοζήση παραμένει προσανατολισμένη στη γη, στη χειρωνακτική εργασία και στην οικογενειακή συνέχεια, με το κρασί να αποτελεί φυσική προέκταση του τόπου και του τρόπου ζωής της οικογένειας.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "kontozisis-organic-vineyards" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
