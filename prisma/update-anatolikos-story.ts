// Κείμενο story για το Anatolikos Vineyards, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στα Άβδηρα της Ξάνθης, στη Θράκη, ο Anatolikos Vineyards καλλιεργεί έναν αμπελώνα που βρίσκεται μόλις λίγα χιλιόμετρα από το Θρακικό Πέλαγος. Η προσπάθεια ξεκίνησε το 2005, με στόχο την ανάδειξη του ιδιαίτερου terroir της περιοχής μέσα από πιστοποιημένα βιολογικά κρασιά.",
  "Ο ιδιόκτητος αμπελώνας αναπτύσσεται στους άνυδρους λόφους των Αβδήρων, σε υψόμετρο 50–70 μέτρων, όπου το αμμώδες έδαφος, οι θαλάσσιες επιρροές και οι δροσεροί βορειοανατολικοί άνεμοι δημιουργούν ένα ξεχωριστό μικροκλίμα. Η φιλοσοφία του οινοποιείου συνδέεται με τη βιολογική καλλιέργεια και την ανάδειξη τόσο των ελληνικών όσο και των διεθνών ποικιλιών της περιοχής.",
  "Ο Anatolikos Vineyards αποτελεί μέρος της σύγχρονης προσπάθειας αναβίωσης του ιστορικού αμπελώνα των Αβδήρων, συνδέοντας τη μακραίωνη οινική παράδοση της Θράκης με μια σύγχρονη, βιώσιμη προσέγγιση στην παραγωγή κρασιού.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "anatolikos-vineyards" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
