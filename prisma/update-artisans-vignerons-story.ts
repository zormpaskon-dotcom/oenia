// Κείμενο story για το Artisans Vignerons de Naoussa, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στη Νάουσα, στην καρδιά μιας από τις σημαντικότερες ζώνες του Ξινόμαυρου στη Βόρεια Ελλάδα, οι Artisans Vignerons de Naoussa αποτελούν ένα συλλογικό εγχείρημα ανθρώπων του αμπελιού με κοινή φιλοσοφία γύρω από την ανάδειξη του τοπικού terroir.",
  "Η προσέγγισή τους βασίζεται στην πιστοποιημένη βιολογική καλλιέργεια και στην επιλογή σταφυλιών από αμπελώνες της Νάουσας και ευρύτερα της Μακεδονίας. Οι αμπελώνες βρίσκονται σε λοφώδεις περιοχές, σε υψόμετρα έως περίπου 400 μέτρα, με ασβεστολιθικά εδάφη και υπέδαφος από γρανίτη και σχιστόλιθο, ενώ το ηπειρωτικό κλίμα και οι ορεινοί άνεμοι συμβάλλουν στη σταδιακή ωρίμαση του σταφυλιού.",
  "Στο οινοποιητικό τους ύφος κυριαρχούν οι ήπιες παρεμβάσεις, η χρήση γηγενών ζυμών και η προσπάθεια να διατηρείται καθαρός ο χαρακτήρας της ποικιλίας και του τόπου. Στο επίκεντρο βρίσκεται το Ξινόμαυρο, ενώ το portfolio επεκτείνεται και σε άλλες ελληνικές και διεθνείς ποικιλίες μέσα από το ευρύτερο project Artisans Vignerons du Nord.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "artisans-vignerons-de-naoussa" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
