// Αντικατάσταση του γενικόλογου story + προσθήκη philosophy για το Oenops
// Wines, με πιο τεκμηριωμένο κείμενο που δόθηκε αυτούσιο από τον χρήστη
// (περιέχει συγκεκριμένα στοιχεία — Προσοτσάνη, σπουδές στο Μπορντό, δεκαετία
// στο Κτήμα Παυλίδη, σειρές APLA/DOTS/RAW — που έλειπαν πριν).
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στην Προσοτσάνη της Δράμας, η Oenops Wines αποτελεί ένα σύγχρονο οινοποιητικό εγχείρημα με επίκεντρο τις ελληνικές γηγενείς ποικιλίες και την έκφραση διαφορετικών αμπελοτόπων. Πίσω από το project βρίσκεται ο Νίκος Καρατζάς, γεννημένος στη Δράμα, με σπουδές χημικού μηχανικού στη Θεσσαλονίκη και οινολογίας στο Μπορντό. Πριν δημιουργήσει την Oenops, εργάστηκε για περισσότερο από μία δεκαετία στο Κτήμα Παυλίδη.",
  "Η Oenops δημιουργήθηκε με μια διαφορετική προσέγγιση: χωρίς ιδιόκτητους αμπελώνες, αλλά με ένα δίκτυο επιλεγμένων αμπελουργών από διαφορετικές περιοχές της Ελλάδας. Η συνεργασία με τους ανθρώπους που καλλιεργούν τα αμπέλια αποτελεί βασικό μέρος του μοντέλου της, επιτρέποντας στην ομάδα να αναζητά παλιά αμπέλια, ιδιαίτερα terroirs και ποικιλίες με ξεχωριστό χαρακτήρα.",
  "Σήμερα, η βάση της Oenops βρίσκεται στη Δράμα, ενώ τα κρασιά της προέρχονται από διαφορετικές περιοχές της χώρας. Από τις σειρές APLA και DOTS μέχρι τη RAW, κάθε οικογένεια κρασιών εξερευνά διαφορετικές πλευρές του ελληνικού αμπελώνα, έχοντας κοινό σημείο αναφοράς την καθαρότητα της ποικιλίας και του τόπου.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία της Oenops Wines βασίζεται στην προσπάθεια να αφήνεται το σταφύλι και ο τόπος να εκφράζονται όσο γίνεται πιο καθαρά. Η εταιρεία δουλεύει αποκλειστικά με ελληνικές γηγενείς ποικιλίες, αναζητώντας διαφορετικά terroirs και παλιά αμπέλια μέσα από ένα δίκτυο συνεργαζόμενων αμπελουργών σε ολόκληρη την Ελλάδα.",
  "Στον αμπελώνα, η συνεργασία με τους παραγωγούς αποτελεί βασικό μέρος της προσέγγισης. Η ομάδα της Oenops παρακολουθεί στενά την πρώτη ύλη και εργάζεται μαζί με τους καλλιεργητές, ενώ κάθε αμπελώνας αντιμετωπίζεται ξεχωριστά. Στο οινοποιείο, οι παρεμβάσεις παραμένουν περιορισμένες: οινοποιήσεις πραγματοποιούνται σε πήλινους αμφορείς, τσιμεντένιες δεξαμενές και ουδέτερα δοχεία, αποφεύγοντας τη βαριά χρήση νέου βαρελιού ώστε να παραμένουν καθαρά τα χαρακτηριστικά της ποικιλίας και του terroir.",
  "Η ίδια λογική γίνεται ακόμη πιο εμφανής στη σειρά RAW, όπου παλιά αμπέλια, αυθόρμητες ζυμώσεις, αμφορείς και τσιμέντο χρησιμοποιούνται για κρασιά με ελάχιστη παρέμβαση. Στη σειρά DOTS, αντίστοιχα, η έμφαση βρίσκεται στη μονοποικιλιακή έκφραση γηγενών ποικιλιών από επιλεγμένα terroirs.",
  "Για τον Νίκο Καρατζά, η διαδικασία ξεκινά από την ακρόαση: του αμπελουργού, του σταφυλιού, της γης και της κάθε χρονιάς. Αυτή η προσέγγιση οδηγεί σε κρασιά σύγχρονα αλλά βαθιά ριζωμένα στον ελληνικό αμπελώνα.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "oenops-wines" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story (αντικαταστάθηκε) + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
