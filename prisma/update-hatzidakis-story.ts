// Κείμενο story για το Hatzidakis Winery, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στον Πύργο Καλλίστης της Σαντορίνης, το Hatzidakis Winery γεννήθηκε το 1997 από τον Χαρίδημο Χατζηδάκη και την Κωνσταντίνα Χρυσού, μέσα από έναν παλιό οικογενειακό αμπελώνα που είχε παραμείνει ακαλλιέργητος για δεκαετίες. Ο αμπελώνας βρίσκεται σε υψόμετρο περίπου 330 μέτρων και καλλιεργήθηκε ξανά με βιολογικές πρακτικές, αποτελώντας την αφετηρία για τη δημιουργία ενός μικρού υπόσκαφου οινοποιείου μέσα σε φυσική σπηλιά — μια παραδοσιακή «κάναβα» της Σαντορίνης.",
  "Οι πρώτες ετικέτες κυκλοφόρησαν το 1998, με το Ασύρτικο και το Μαυροτράγανο να βρίσκονται από την αρχή στον πυρήνα της παραγωγής. Η προσέγγιση του Χαρίδημου Χατζηδάκη βασίστηκε στην ανάδειξη των γηγενών ποικιλιών και στη βελτίωση της ποιότητας του σαντορινιού αμπελώνα, με ιδιαίτερη έμφαση στην οργανική καλλιέργεια και στις διαφορετικές εκφράσεις των αμπελοτοπιών.",
  "Σήμερα, η οινοποιητική ομάδα συνεχίζει αυτή την κληρονομιά, δουλεύοντας με Ασύρτικο, Αηδάνι, Μαυροτράγανο και Βουδόματο. Η φιλοσοφία παραμένει προσανατολισμένη στην αυθεντική έκφραση της Σαντορίνης, μέσα από μικρές οινοποιήσεις, παραδοσιακές τεχνικές και κρασιά με έντονη σχέση με τον τόπο.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "hatzidakis" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
