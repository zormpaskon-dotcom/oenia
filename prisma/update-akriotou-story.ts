// Κείμενο story για την Ακριώτου Μικροοινοποιία, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στις Πλαταιές Βοιωτίας, στους πρόποδες του Κιθαιρώνα, η Ακριώτου Μικροοινοποιία δημιουργεί κρασιά με αφετηρία τον αμπελώνα και βαθιά σχέση με τον τόπο. Η οινολόγος Βασιλική Ακριώτου ίδρυσε τη δική της σειρά κρασιών το 2015, μεταφέροντας σε κάθε ετικέτα τη γνώση, την εμπειρία και τη δική της οπτική πάνω στις ελληνικές ποικιλίες.",
  "Ο οικογενειακός αμπελώνας, σε υψόμετρο 280–380 μέτρων, αποτελεί την καρδιά της προσπάθειας, ενώ επιλεγμένοι συνεργαζόμενοι αμπελώνες συμπληρώνουν την πρώτη ύλη από τη Στερεά Ελλάδα και την ορεινή Αιγιάλεια. Σαββατιανό, Ασύρτικο και Μαλαγουζιά βρίσκονται στο επίκεντρο, με στόχο κρασιά καθαρά, εκφραστικά και συνδεδεμένα με την προέλευσή τους.",
  "Το μικρό οινοποιείο στις Πλαταιές, που δημιουργήθηκε το 2017, είναι σχεδιασμένο για μικρές και προσεκτικά ελεγχόμενες οινοποιήσεις. Εδώ, η φιλοσοφία είναι απλή: κάθε ποικιλία να διατηρεί τον χαρακτήρα της και κάθε κρασί να αφήνει να φανεί ο τόπος από τον οποίο προέρχεται.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "akriotou-microwinery" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
