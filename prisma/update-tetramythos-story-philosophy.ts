// Κείμενο story + philosophy για το Tetramythos Winery, δόθηκε αυτούσιο από τον χρήστη
// (χωρίς τα inline citation links του αρχικού κειμένου, όπως ζητήθηκε).
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στην Άνω Διακοπτή Αιγιάλειας, στις πλαγιές του Χελμού, η Tetramythos Winery γεννήθηκε μέσα από την οικογενειακή σχέση των αδελφών Άριστου και Στάθη Σπανού με την αμπελουργία. Μεγαλωμένοι σε μια περιοχή με μακρά αμπελουργική παράδοση, ξεκίνησαν αρχικά ως αμπελουργοί, καλλιεργώντας παράλληλα και άλλες οικογενειακές καλλιέργειες.",
  "Το 1999 γνώρισαν τον οινολόγο Παναγιώτη Παπαγιαννόπουλο, επίσης από την περιοχή, και η συνεργασία τους έδωσε νέα κατεύθυνση στο εγχείρημα. Την ίδια χρονιά κυκλοφόρησαν οι πρώτες φιάλες Tetramythos. Ακολούθησαν νέες φυτεύσεις, συνεργασίες με παραγωγούς της ευρύτερης περιοχής και η δημιουργία ενός σύγχρονου οινοποιείου, η κατασκευή του οποίου ξεκίνησε το 2003 και ολοκληρώθηκε το 2004.",
  "Σήμερα, οι ιδιόκτητοι και συνεργαζόμενοι αμπελώνες βρίσκονται στην ορεινή Αιγιάλεια, σε υψόμετρα περίπου 450–1.000 μέτρων. Το τοπικό μικροκλίμα, τα εδάφη και η επίδραση του Κορινθιακού δημιουργούν ένα ιδιαίτερο περιβάλλον για την καλλιέργεια. Στο επίκεντρο βρίσκονται τόσο γνωστές όσο και σπάνιες ελληνικές ποικιλίες, με το Μαύρο Καλαβρυτινό να αποτελεί χαρακτηριστικό παράδειγμα της προσπάθειας της Tetramythos να αναδείξει τον τοπικό αμπελώνα.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία της Tetramythos ξεκινά από τον αμπελώνα. Η βιολογική καλλιέργεια αποτελεί βασική επιλογή της οικογένειας και εφαρμόζεται τόσο στους ιδιόκτητους αμπελώνες όσο και μέσα από συνεργασίες με παραγωγούς της ορεινής Αιγιάλειας. Στόχος είναι η παραγωγή υγιούς και ποιοτικής πρώτης ύλης, με σεβασμό στις ιδιαιτερότητες του ορεινού περιβάλλοντος.",
  "Η θέση των αμπελώνων, σε υψόμετρα από περίπου 450 έως 1.000 μέτρα, προσφέρει διαφορετικές συνθήκες ανάλογα με το υψόμετρο, την έκθεση, το έδαφος και την επίδραση του Κορινθιακού. Η οικογένεια αξιοποιεί αυτές τις διαφορές για να εξερευνήσει τόσο καθιερωμένες όσο και λιγότερο γνωστές ποικιλίες.",
  "Ιδιαίτερη θέση έχει το Μαύρο Καλαβρυτινό, μία σπάνια τοπική ποικιλία που η Tetramythos εμφιαλώνει ως μονοποικιλιακό κρασί. Παράλληλα, η γκάμα περιλαμβάνει Ροδίτη, Μαλαγουζιά, Αγιωργίτικο, Cabernet Sauvignon και Ρετσίνα.",
  "Στο οινοποιείο, η οικογένεια συνδυάζει τη σύγχρονη τεχνογνωσία με διαφορετικές μεθόδους οινοποίησης, επιδιώκοντας να διατηρεί την καθαρότητα της ποικιλίας και του τόπου. Η έρευνα, οι νέες φυτεύσεις και οι πειραματισμοί αποτελούν μέρος της καθημερινής εξέλιξης του κτήματος. Η βασική κατεύθυνση παραμένει σταθερή: βιολογικός αμπελώνας, τοπικές ποικιλίες και κρασιά που έχουν σαφή σχέση με την ορεινή Αιγιάλεια.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "tetramythos-winery" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
