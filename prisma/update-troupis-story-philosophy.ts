// Κείμενο story + philosophy για το Troupis Winery, δόθηκε αυτούσιο από τον χρήστη
// (χωρίς τα inline citation links του αρχικού κειμένου, όπως ζητήθηκε).
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στην καρδιά του οροπεδίου της Μαντινείας, στην περιοχή Φτέρη, η οικογένεια Τρουπή ασχολείται με την αμπελουργία από τη δεκαετία του 1970. Αρχικά καλλιεργούσε τα δικά της αμπέλια και παρήγαγε κρασί για την οικογένεια, διαθέτοντας την υπόλοιπη παραγωγή σε άλλους παραγωγούς.",
  "Η σύγχρονη ιστορία του οινοποιείου ξεκίνησε το 2010, όταν η οικογένεια αποφάσισε να επενδύσει στους ιδιόκτητους αμπελώνες της, συνολικής έκτασης περίπου 70 στρεμμάτων. Από τότε, η εγκατάσταση εξελίχθηκε σταδιακά σε ένα σύγχρονο οινοποιείο, με νέους χώρους, εξοπλισμό και ανθρώπινο δυναμικό.",
  "Οι αμπελώνες βρίσκονται περίπου στα 650–700 μέτρα, σε διαφορετικές θέσεις της Φτέρης, όπως τα Λιθαράκια, η Καταρράχια και το Μπελμπέρι. Το Μοσχοφίλερο αποτελεί τον βασικό πρωταγωνιστή, ενώ τα τελευταία χρόνια η οικογένεια έχει φυτέψει και Ασύρτικο, εξερευνώντας την προσαρμογή του στην περιοχή. Η παραγωγή της Troupis έχει εξελιχθεί πέρα από το κλασικό στυλ της Μαντινείας, με διαφορετικές σειρές και μεθόδους που επιτρέπουν στην ποικιλία να εκφράζεται με διαφορετικούς τρόπους.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία της Troupis Winery περιστρέφεται γύρω από το Μοσχοφίλερο, αλλά δεν περιορίζεται σε μία μόνο έκφραση της ποικιλίας. Η οικογένεια αναζητά διαφορετικούς τρόπους να αναδείξει τον χαρακτήρα του αμπελώνα της Μαντινείας, συνδυάζοντας το τοπικό terroir με πειραματισμό και σύγχρονες τεχνικές.",
  "Στους αμπελώνες δίνεται έμφαση στις χαμηλές αποδόσεις, στην ήπια διαχείριση του περιβάλλοντος και στη συνεχή βελτίωση της καλλιέργειας. Παράλληλα, η οικογένεια πειραματίζεται με διαφορετικά υποκείμενα και έχει δημιουργήσει φυτεύσεις ξεχασμένων ποικιλιών της Μαντινείας, όπως το Κολλινιάτικο.",
  "Στο οινοποιείο χρησιμοποιούνται κεραμικά δοχεία, τσιμεντένιες δεξαμενές, βαρέλια δρυός και ακακίας, ενώ σε επιλεγμένα κρασιά εφαρμόζονται παρατεταμένες εκχυλίσεις, γηγενείς ζύμες και ελάχιστες παρεμβάσεις. Αυτή η πολυμορφία επιτρέπει στην ομάδα να εξετάζει διαφορετικές διαστάσεις του Μοσχοφίλερου και άλλων ελληνικών ποικιλιών.",
  "Η προσέγγιση της Troupis είναι επομένως ξεκάθαρη: βαθιά γνώση της Μαντινείας, σεβασμός στην πρώτη ύλη και συνεχής πειραματισμός γύρω από το τι μπορεί να δώσει ο αμπελώνας.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "troupis-winery" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
