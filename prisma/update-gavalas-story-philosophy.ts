// Κείμενο story + philosophy για το Gavalas Winery, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στο Μεγαλοχώρι της Σαντορίνης, η οικογένεια Γαβαλά ασχολείται με την αμπελουργία και την οινοποίηση εδώ και περίπου τρεις αιώνες. Η ιστορία της ξεκινά στα τέλη του 18ου αιώνα, όταν η πρώτη γενιά παρήγαγε κρασί κυρίως για την οικογένεια, διαθέτοντας παράλληλα μέρος της παραγωγής στην τοπική αγορά. Στις αρχές του 20ού αιώνα τα κρασιά ταξίδευαν ήδη εκτός νησιού, με την οικογένεια να εξάγει στην Αλεξάνδρεια και αργότερα να προμηθεύει την Αθήνα και τον Πειραιά.",
  "Το σημερινό οινοποιείο στεγάζεται σε μια παραδοσιακή πέτρινη κάναβα, όπου έχουν διατηρηθεί τα παλιά κελάρια, τα πατητήρια και οι χαρακτηριστικές είσοδοι του αρχικού χώρου. Το 1998 η οικογένεια εμφιάλωσε για πρώτη φορά τη δική της παραγωγή, ενώ από το 2004 το οινοποιείο άνοιξε τις πόρτες του για επισκέπτες.",
  "Σήμερα, ο Γιώργος Γαβαλάς εκπροσωπεί την τέταρτη γενιά και ο γιος του Βαγγέλης την πέμπτη. Το οινοποιείο συνδυάζει την παραδοσιακή κάναβα με σύγχρονο εξοπλισμό και παράγει περίπου δέκα ετικέτες, με επίκεντρο τον χαρακτήρα του σαντορινιού αμπελώνα.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία του Οινοποιείου Γαβαλά είναι άμεσα συνδεδεμένη με την προσπάθεια να εκφραστεί ο χαρακτήρας του σαντορινιού terroir μέσα από τις γηγενείς ποικιλίες του νησιού. Το Ασύρτικο βρίσκεται στον πυρήνα της παραγωγής, ενώ παράλληλα το οινοποιείο έχει επενδύσει συστηματικά στην ανάδειξη λιγότερο γνωστών ποικιλιών, όπως το Κατσάνο, το Βουδομάτο και το Μαυροτράγανο. Το 2006 έγινε η πρώτη προσπάθεια αναβίωσης του Κατσάνου, μιας σπάνιας ποικιλίας που καταλαμβάνει πολύ μικρό μέρος του αμπελώνα της Σαντορίνης.",
  "Η προσέγγιση ξεκινά από τον ίδιο τον αμπελώνα. Οι ιδιαίτερες συνθήκες του νησιού — τα ηφαιστειακά εδάφη, οι χαμηλές βροχοπτώσεις και οι ισχυροί άνεμοι — έχουν διαμορφώσει έναν αμπελώνα με χαμηλές φυσικές αποδόσεις και παραδοσιακά συστήματα διαμόρφωσης, όπως η κουλούρα.",
  "Στο οινοποιείο, η παράδοση δεν αντιμετωπίζεται ως μουσειακό στοιχείο. Οι αυθεντικοί χώροι της παλιάς κάναβας διατηρούνται δίπλα σε σύγχρονο εξοπλισμό, επιτρέποντας στην οικογένεια να συνδυάζει την ιστορική γνώση με σύγχρονες πρακτικές οινοποίησης. Από το κλασικό Ασύρτικο έως το Vinsanto και τις σπάνιες γηγενείς ποικιλίες, στόχος είναι κάθε ετικέτα να λειτουργεί ως διαφορετική έκφραση της Σαντορίνης.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "gavalas-winery" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
