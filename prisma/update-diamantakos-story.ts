// Κείμενο story για το Κτήμα Διαμαντάκος, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στην καρδιά της ζώνης ΠΟΠ Νάουσα, στη θέση Μαντέμι, το Κτήμα Διαμαντάκος είναι ένα μικρό οικογενειακό οινοποιείο που έχει χτίσει την ταυτότητά του γύρω από τον αμπελώνα και τις γηγενείς ποικιλίες της περιοχής. Η ιστορία της οικογένειας ξεκινά από τον Γιώργο Διαμαντάκο, αμπελουργό πρώτης γενιάς, και συνεχίζεται μέσα από τρεις γενιές που συνδέουν την αμπελουργία με τη σύγχρονη οινοποίηση.",
  "Το 1978 η οικογένεια απέκτησε την έκταση όπου βρίσκονται σήμερα το οινοποιείο και οι αμπελώνες, ενώ το 1998 ο Ευάγγελος Διαμαντάκος, δεύτερη γενιά αμπελουργός και οινοποιός, εμφιάλωσε το πρώτο κρασί του κτήματος. Από το 2005, ο Γιώργος Διαμαντάκος, τρίτη γενιά, ανέλαβε την πορεία του κτήματος, φέρνοντας μαζί του σπουδές στην οινολογία και την αμπελουργία και μια πιο σύγχρονη ματιά στη Νάουσα.",
  "Στο επίκεντρο βρίσκονται το Ξινόμαυρο και το Πρεκνάδι, δύο γηγενείς ποικιλίες που εκφράζουν το ιδιαίτερο οικοσύστημα της περιοχής. Η καλλιέργεια και οι εργασίες από το αμπέλι μέχρι την εμφιάλωση πραγματοποιούνται χειρωνακτικά, με έμφαση στη βιοποικιλότητα και στον περιορισμό των παρεμβάσεων.",
  "Η φιλοσοφία του Κτήματος Διαμαντάκος είναι απλή και ξεκάθαρη: να εκφράσει μέσα από το κρασί τον τόπο της Νάουσας και τις δύο γηγενείς ποικιλίες του, συνδυάζοντας την οικογενειακή παράδοση με μια σύγχρονη, προσωπική προσέγγιση.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "diamantakos" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
