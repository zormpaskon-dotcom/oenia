import { prisma } from "../lib/prisma";

const story =
  "Το Κτήμα Μπαϊρακτάρη είναι μια απόδειξη της αφοσίωσης της οικογένειάς μας στην τέχνη της οινοποίησης. Οι αμπελώνες μας καλλιεργούνται εδώ και τρεις γενιές στη Νεμέα, παράγοντας τα καλύτερα σταφύλια του Αγιωργίτικου. Αυτή η ποικιλία είναι η ψυχή των κρασιών μας, φημισμένη για το εξαιρετικό προφίλ της. Το ταξίδι μας ξεκίνησε το 2005, με γνώμονα το πάθος για την παραγωγή κρασιών που τιμούν την κληρονομιά μας. Με τις επεκτάσεις το 2008 και το 2024, εξελισσόμαστε συνεχώς, βελτιώνοντας τις εγκαταστάσεις μας. Σήμερα, παράγουμε εξαιρετικής ποιότητας κρασιά, μοιράζοντας τη μοναδική γεύση της Νεμέας με τους λάτρεις του κρασιού στην Ελλάδα, την ΕΕ και τις ΗΠΑ. Στο Κτήμα Μπαϊρακτάρη, είμαστε αφοσιωμένοι στη βιωσιμότητα και την καινοτομία, διασφαλίζοντας ότι κάθε φιάλη αντανακλά την κληρονομιά της οικογένειάς μας και το Αγιωργίτικο.";

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "bairaktaris" },
    data: { story },
  });
  console.log(`✓ ${winery.name} -> story updated (${story.length} chars)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
