// Κείμενο story για το Κτήμα Ρωξάνη Μάτσα, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στην Κάντζα Αττικής, σε έναν από τους ιστορικούς αμπελώνες των Μεσογείων, το Κτήμα Μάτσα αποτελεί σημείο αναφοράς για τη σύγχρονη ιστορία του αττικού κρασιού. Ο αμπελώνας έχει ιστορία που ξεκινά από το 1878 και αποτελεί μέρος μιας ευρύτερης οινικής κληρονομιάς που συνδέεται με την οικογένεια Μάτσα και την ιστορία της αμπελουργίας της περιοχής.",
  "Κεντρική μορφή στη σύγχρονη πορεία του κτήματος είναι η Ρωξάνη Μάτσα, η οποία το 1976 δημιούργησε τον δικό της αμπελώνα πάνω σε τμήμα της οικογενειακής γης. Από τα τέλη της δεκαετίας του 1970 συνεργάστηκε με την Μπουτάρη, συνδυάζοντας την προσωπική της παρουσία στον αμπελώνα με την τεχνογνωσία μιας μεγάλης ελληνικής οινοποιίας. Το 2001 ανακηρύχθηκε «Οινική Προσωπικότητα της Χρονιάς» από την Ένωση Ελλήνων Δημοσιογράφων Οίνου.",
  "Ο αμπελώνας, συνολικής έκτασης 122 στρεμμάτων, καλλιεργείται σύμφωνα με τις αρχές της βιολογικής γεωργίας. Η Μαλαγουζιά αποτελεί μία από τις χαρακτηριστικές ποικιλίες του κτήματος, μαζί με το Σαββατιανό, το Ασύρτικο, τον Ροδίτη, το Syrah και το Sauvignon Blanc.",
  "Η φιλοσοφία του Κτήματος Μάτσα βασίζεται στη στενή σχέση με τον αμπελώνα, στη διατήρηση της ιστορικής του συνέχειας και στην ανάδειξη των δυνατοτήτων του αττικού terroir μέσα από σύγχρονες οινοποιητικές πρακτικές.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "matsa-estate" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
