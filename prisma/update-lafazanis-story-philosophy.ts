// Κείμενο story + philosophy για το Lafazanis Winery, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στις Αρχαίες Κλεωνές της Νεμέας, το Κτήμα Λαφαζάνη συνεχίζει μια οικογενειακή οινοποιητική πορεία που ξεκίνησε το 1946. Η ιστορία της οικογένειας άρχισε στον Πειραιά, όπου ο Βασίλης Λαφαζάνης παρήγαγε για πρώτη φορά κρασί και, έναν χρόνο αργότερα, απέκτησε την πρώτη επίσημη άδεια οινοποίησης. Το 1960 δημιουργήθηκε το πρώτο ιδιόκτητο οικογενειακό οινοποιείο στη Μαγούλα Αττικής.",
  "Καθοριστική στιγμή αποτέλεσε η είσοδος του Σπύρου Λαφαζάνη στη δεύτερη γενιά, μετά τις σπουδές του ως Χημικός–Οινολόγος. Το 1993 η παραγωγή μεταφέρθηκε στη ζώνη ΠΟΠ Νεμέα, σηματοδοτώντας τη βαθύτερη σύνδεση του οινοποιείου με τον πελοποννησιακό αμπελώνα. Σήμερα, η τρίτη γενιά, η Αθηνά και ο Βασίλης Λαφαζάνης, συμμετέχει ενεργά στην πορεία της οικογένειας.",
  "Το Κτήμα καλλιεργεί ιδιόκτητους αμπελώνες στη Νεμέα και τη Μαντινεία, ενώ παράλληλα συνεργάζεται με περισσότερους από 300 αμπελουργούς. Η σύγχρονη ταυτότητά του παραμένει προσανατολισμένη στις ελληνικές ποικιλίες και στην εξέλιξη της οικογενειακής παράδοσης.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία του Κτήματος Λαφαζάνη στηρίζεται σε τρεις βασικούς άξονες: γνώση, σεβασμό στο ελληνικό σταφύλι και διαρκή εξέλιξη. Η οικογένεια αντιμετωπίζει το κρασί ως αποτέλεσμα της σχέσης ανάμεσα στον άνθρωπο, τη φύση και τον χρόνο, με στόχο κρασιά που εκφράζουν την ποικιλία και τον τόπο τους, αλλά παραμένουν προσιτά και ευέλικτα στο τραπέζι.",
  "Η αμπελουργική προσέγγιση συνδυάζει ιδιόκτητους αμπελώνες συμβατικής καλλιέργειας ακριβείας με βιολογικούς αμπελώνες. Σήμερα καλλιεργούνται 160 στρέμματα ιδιόκτητων αμπελώνων συμβατικής διαχείρισης και 170 στρέμματα βιολογικά, ενώ ένας νέος ενιαίος αμπελώνας 300 στρεμμάτων στην περιοχή Τσούρκα της Νεμέας βρίσκεται σε εξέλιξη. Εκεί εφαρμόζονται αποκλειστικά βιολογικές πρακτικές και έχουν φυτευτεί, μεταξύ άλλων, Κοτσιφολιά, Βιδιανό και Μαυροτράγανο.",
  "Παράλληλα, η φιλοσοφία της οικογένειας αφήνει χώρο για πειραματισμό. Δίπλα στο Αγιωργίτικο, το Μοσχοφίλερο, τη Μαλαγουζιά και το Ασύρτικο, η σειρά Break the Glass εξερευνά πιο απρόσμενους συνδυασμούς ποικιλιών, όπως Αγιωργίτικο με Tempranillo και Μαλαγουζιά με Σιδερίτη.",
  "Η βιωσιμότητα αποτελεί επίσης πρακτικό μέρος της λειτουργίας, με φωτοβολταϊκά, ανακύκλωση, επεξεργασία υγρών αποβλήτων, κομποστοποίηση και αξιοποίηση του βρόχινου νερού.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "lafazanis-winery" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
