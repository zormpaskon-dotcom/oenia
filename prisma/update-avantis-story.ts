import { prisma } from "../lib/prisma";

const STORY = `Η ιστορία του Κτήματος Αβαντίς ξεκινά τον 19ο αιώνα, όταν η οικογένεια Μούντριχα εγκαταστάθηκε στη γη της Εύβοιας και δημιούργησε μια παράδοση που πέρασε από γενιά σε γενιά. Η καλλιέργεια της γης και η αγάπη για το αμπέλι αποτέλεσαν τον πυρήνα αυτής της οικογενειακής ιστορίας, μέχρι την πρώτη οινοποίηση του Απόστολου Μούντριχα το 1994, σηματοδοτώντας την αρχή της σύγχρονης πορείας του Κτήματος.

Σήμερα, το Αβαντίς είναι ένα boutique οινοποιείο στην κεντρική Εύβοια, με φιλοσοφία που βασίζεται στην ανάδειξη του δυναμικού του ευβοϊκού αμπελώνα. Οι αμπελώνες του βρίσκονται στο Αφράτι και τον Μύτικα, σε διαφορετικά υψόμετρα και μικροκλίματα που επηρεάζονται από το όρος Δίρφη και τον Ευβοϊκό κόλπο. Οι ψυχροί άνεμοι, τα ζεστά καλοκαίρια και το ξηρό φθινόπωρο δημιουργούν συνθήκες που ευνοούν την αργή και ποιοτική ωρίμαση των σταφυλιών.

Στους αμπελώνες συνυπάρχουν ελληνικές και διεθνείς ποικιλίες, με ιδιαίτερη έμφαση στο Syrah αλλά και στη Μαυροκουντούρα, μια παλιά ευβοϊκή ποικιλία που το Κτήμα συνέβαλε στην αναβίωσή της. Η αναζήτηση της ταυτότητας του τόπου, η έρευνα πάνω στις ποικιλίες και η προσεκτική οινοποίηση βρίσκονται στον πυρήνα της φιλοσοφίας του.

Από την οικογενειακή παράδοση μέχρι τη σύγχρονη οινοποιητική προσέγγιση, το Αβαντίς παραμένει προσηλωμένο σε έναν στόχο: να εκφράσει μέσα από το κρασί τον χαρακτήρα της Εύβοιας. Ένα οινοποιείο με βαθιές ρίζες, σύγχρονη ματιά και ξεκάθαρη επιθυμία να δημιουργεί κρασιά που δίνουν στην ευβοϊκή γη τη θέση που της αξίζει στον ελληνικό αμπελώνα.`;

async function main() {
  const winery = await prisma.winery.findUnique({ where: { slug: "avantis-estate" }, select: { id: true, story: true } });
  if (!winery) throw new Error("Winery avantis-estate not found");
  if (winery.story !== null) {
    throw new Error(`Winery "avantis-estate" story δεν είναι null όπως αναμενόταν — abort χωρίς αλλαγές.\nΤρέχον: ${JSON.stringify(winery.story)}`);
  }
  await prisma.winery.update({ where: { id: winery.id }, data: { story: STORY } });
  console.log('✓ Winery "avantis-estate" story ενημερώθηκε.');
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
