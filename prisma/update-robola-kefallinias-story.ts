// Κείμενο story για τον Συνεταιρισμό Παραγωγών Ρομπόλας Κεφαλληνίας (Ορεάλιος Γη), δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στην καρδιά της αμπελουργικής ζώνης Ρομπόλας, στα Ομαλά Κεφαλονιάς, η Ορεάλιος Γη αποτελεί τη σύγχρονη συνέχεια του Συνεταιρισμού Παραγωγών Ρομπόλας Κεφαλληνίας, που ιδρύθηκε το 1982 από τους αμπελουργούς της περιοχής με στόχο να προστατεύσει και να αναδείξει τον ιδιαίτερο χαρακτήρα του κεφαλονίτικου αμπελώνα. Η πρώτη συγκέντρωση σταφυλιών και η εμφιάλωση ξεκίνησαν το 1983, ενώ το 1987 ο συνεταιρισμός απέκτησε το δικό του οινοποιείο, σε υψόμετρο περίπου 410 μέτρων, δίπλα στη Μονή Αγίου Γερασίμου.",
  "Σήμερα ο συνεταιρισμός αριθμεί περίπου 300 αμπελουργούς, οι οποίοι καλλιεργούν τους δικούς τους αμπελώνες στη ζώνη Ρομπόλας. Οι αμπελώνες αναπτύσσονται στις πλαγιές και το οροπέδιο των Ομαλών, σε υψόμετρα από περίπου 300 έως 800 μέτρα, σε φτωχά, χαλικώδη και ασβεστολιθικά εδάφη, με την επίδραση του ορεινού μικροκλίματος και της θαλάσσιας αύρας.",
  "Στο επίκεντρο βρίσκεται η Ρομπόλα, η χαρακτηριστική λευκή ποικιλία της Κεφαλονιάς και βάση του ΠΟΠ Ρομπόλα Κεφαλληνίας. Παράλληλα, ο συνεταιρισμός αξιοποιεί και άλλες γηγενείς ποικιλίες του νησιού, όπως Βοστιλίδι, Μοσχάτο και Μαυροδάφνη.",
  "Η φιλοσοφία της Ορεάλιος Γη συνδυάζει τη συλλογική δύναμη των αμπελουργών με τη σύγχρονη οινοποίηση, έχοντας ως σταθερό σημείο αναφοράς τον κεφαλονίτικο αμπελώνα και την ανάδειξη της Ρομπόλας ως μιας από τις χαρακτηριστικές ποικιλίες του ελληνικού κρασιού.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "synetairismos-robolas-kefallinias" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
