// Κείμενο philosophy για το Domaine Hatzimichalis, δόθηκε αυτούσιο από τον χρήστη.
// Το υπάρχον story παραμένει άθικτο.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const PHILOSOPHY = [
  "Η φιλοσοφία του Κτήματος Χατζημιχάλη ξεκινά από την αντίληψη ότι κάθε αμπελώνας έχει τη δική του ταυτότητα. Στην Κοιλάδα της Αταλάντης, το έδαφος, το υψόμετρο, ο προσανατολισμός, η ηλικία των αμπέλων και το ιδιαίτερο μικροκλίμα δημιουργούν ένα σύνθετο μωσαϊκό αμπελοτοπιών, το οποίο αποτελεί τη βάση για διαφορετικές εκφράσεις του κρασιού.",
  "Η περιοχή χαρακτηρίζεται από τις δροσερές αέριες μάζες που κατεβαίνουν από τον Παρνασσό και συναντούν τη θαλάσσια αύρα του Ευβοϊκού, δημιουργώντας συνθήκες που ευνοούν την ομαλή ωρίμαση των σταφυλιών. Τα αργιλοασβεστολιθικά εδάφη, σε συνδυασμό με τις διαφορετικές θέσεις των αμπελώνων, επιτρέπουν την καλλιέργεια τόσο ελληνικών όσο και διεθνών ποικιλιών.",
  "Στο οινοποιείο, η προσέγγιση βασίζεται σε μικρές και ξεχωριστές οινοποιήσεις ανά terroir, με τη σύγχρονη τεχνολογία να λειτουργεί συμπληρωματικά προς την παράδοση. Το Cabernet Sauvignon, το Merlot και το Chardonnay συνυπάρχουν με ελληνικές ποικιλίες, ενώ ιδιαίτερη σημασία δίνεται στην ανάδειξη της προέλευσης κάθε κρασιού.",
  "Παράλληλα, η βιωσιμότητα αποτελεί πλέον αναπόσπαστο μέρος της φιλοσοφίας του Κτήματος, με πρακτικές εξοικονόμησης νερού, αξιοποίησης των υποπροϊόντων του τρύγου, περιορισμού των αποβλήτων και χρήσης ανακυκλώσιμων υλικών.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "domaine-hatzimichalis" },
    data: { philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: philosophy ενημερώθηκε (${PHILOSOPHY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
