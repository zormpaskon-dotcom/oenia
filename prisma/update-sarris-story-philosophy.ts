// Κείμενο story + philosophy για το Sarris Winery, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στα Σβορωνάτα της Κεφαλονιάς, κοντά στην παραλία Άβυθος, η Sarris Winery αποτελεί ένα σύγχρονο boutique οινοποιείο με επίκεντρο τον κεφαλονίτικο αμπελώνα. Ιδρύθηκε το 2016 από τον Panos Sarris, ο οποίος ξεκίνησε το εγχείρημα με έναν μικρό αμπελώνα και λίγα βαρέλια κρασιού, εξελίσσοντάς το σταδιακά σε ένα οινοποιείο με σαφή προσωπική ταυτότητα.",
  "Η θέση της Sarris είναι άμεσα συνδεδεμένη με το τοπίο της νότιας Κεφαλονιάς. Το οινοποιείο βρίσκεται ανάμεσα στους αμπελώνες και τη θάλασσα, σε ένα περιβάλλον όπου τα ασβεστολιθικά εδάφη και η θαλάσσια αύρα αποτελούν βασικά στοιχεία του αμπελουργικού χαρακτήρα.",
  "Στο επίκεντρο βρίσκονται οι τοπικές ποικιλίες του νησιού, με τη Ρομπόλα της Κεφαλονιάς να αποτελεί βασικό σημείο αναφοράς και ποικιλίες όπως η Βοστιλίδι να συμπληρώνουν την παραγωγή. Η Sarris χαρακτηρίζει τα κρασιά της handcrafted και δίνει έμφαση στην οργανική καλλιέργεια και στην περιορισμένη παρέμβαση κατά την οινοποίηση. Το αποτέλεσμα είναι ένα μικρό, ανεξάρτητο οινοποιείο που αντιμετωπίζει την Κεφαλονιά όχι απλώς ως τόπο παραγωγής, αλλά ως βασικό συστατικό της ταυτότητας κάθε κρασιού.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία της Sarris Winery συνοψίζεται στη σχέση ανάμεσα στη θάλασσα, την πέτρα και τον ουρανό της Κεφαλονιάς. Το οινοποιείο επιδιώκει να αποτυπώσει αυτή τη σχέση μέσα από κρασιά με καθαρότητα και έντονη σύνδεση με το τοπικό terroir.",
  "Η βιολογική προσέγγιση στον αμπελώνα και η επιλογή περιορισμένων παρεμβάσεων στην οινοποίηση αποτελούν βασικά στοιχεία αυτής της κατεύθυνσης. Το ενδιαφέρον στρέφεται κυρίως στις γηγενείς ποικιλίες της Κεφαλονιάς, με τη Ρομπόλα να βρίσκεται στο επίκεντρο και τη Βοστιλίδι να προσφέρει μια διαφορετική έκφραση του νησιού.",
  "Η σχέση με τον τόπο δεν αντιμετωπίζεται μόνο ως θεωρητική έννοια. Τα ασβεστολιθικά εδάφη, η εγγύτητα στη θάλασσα και το ιδιαίτερο μικροκλίμα της περιοχής επηρεάζουν άμεσα τις συνθήκες στις οποίες ωριμάζουν τα σταφύλια. Η ομάδα της Sarris επιδιώκει να διατηρεί αυτά τα χαρακτηριστικά όσο το δυνατόν πιο καθαρά μέσα στο κρασί.",
  "Στο οινοποιείο, η προσέγγιση είναι μικρής κλίμακας και χειροποίητη. Η παραγωγή δεν βασίζεται στην ομοιομορφία, αλλά στην προσπάθεια κάθε κρασί να διατηρεί την ταυτότητα της ποικιλίας και της χρονιάς του. Έτσι, η Sarris τοποθετεί την Κεφαλονιά στο επίκεντρο: λιγότερη παρέμβαση, περισσότερη έμφαση στην πρώτη ύλη και στα φυσικά χαρακτηριστικά του νησιού.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "sarris-winery" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
