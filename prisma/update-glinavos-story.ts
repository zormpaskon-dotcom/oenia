// Κείμενο story για το Κτήμα Γκλίναβος, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στη Ζίτσα Ιωαννίνων, στην καρδιά της αμπελουργικής ζώνης της Ηπείρου, το Κτήμα Γκλίναβος έχει συνδέσει την ιστορία του με την ανάδειξη των ιδιαίτερων ποικιλιών και της οινικής παράδοσης της περιοχής. Ιδρυτής του είναι ο Λευτέρης Γκλίναβος, ο οποίος, μετά τις σπουδές του στην οινολογία και την αμπελουργία στο Bordeaux, επέστρεψε στην Ελλάδα και το 1978 ίδρυσε το Κτήμα στην ΠΟΠ ζώνη της Ζίτσας.",
  "Από τις πρώτες του κιόλας χρονιές, το οινοποιείο συνδύασε τις παραδοσιακές ποικιλίες της Ηπείρου με τις σύγχρονες τεχνολογίες οινοποίησης. Η Ντεμπίνα βρίσκεται στο επίκεντρο, μαζί με το Βλάχικο και το Μπεκάρι, ενώ με τα χρόνια ο αμπελώνας εμπλουτίστηκε και με άλλες ελληνικές και διεθνείς ποικιλίες.",
  "Το 1990 η δεύτερη γενιά, με τον Θωμά Γκλίναβο, περνά ενεργά στην επιχείρηση και ξεκινά μια περίοδος εκσυγχρονισμού και ανάπτυξης. Ακολούθησαν νέες εγκαταστάσεις για αφρώδεις και ημιαφρώδεις οίνους, καθώς και η αναβίωση παραδοσιακών κρασιών της Ηπείρου, με χαρακτηριστικό παράδειγμα τον Παλαιοκαιρίσιο.",
  "Η φιλοσοφία του Κτήματος βασίζεται στη διαρκή εξέλιξη χωρίς απομάκρυνση από την παράδοση: αξιοποίηση των γηγενών ποικιλιών της Ζίτσας, σύγχρονη τεχνολογία και συνεχής προσπάθεια για την ανάδειξη της οινικής ταυτότητας της Ηπείρου.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "domaine-glinavos" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
