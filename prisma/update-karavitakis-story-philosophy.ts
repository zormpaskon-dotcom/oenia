// Κείμενο story + philosophy για το Karavitakis Winery, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στα Ποντικιανά Χανίων, στην περιοχή του Κολυμβαρίου, η Karavitakis Winery συνεχίζει μια οικογενειακή σχέση με το αμπέλι που εκτείνεται σε περίπου οκτώ δεκαετίες. Η σύγχρονη μορφή του κτήματος αναπτύχθηκε με επίκεντρο έναν αμπελώνα που συνδυάζει ιδιόκτητα και συνεργαζόμενα αμπελοτόπια, επιλεγμένα ξεχωριστά για κάθε ποικιλία.",
  "Σήμερα, το κτήμα εκτείνεται σε περίπου 150 στρέμματα και περιλαμβάνει αμπελώνες μέσα στο ιδιαίτερο τοπίο των λόφων του Κολυμβαρίου, ανάμεσα σε αμπέλια και ελαιώνες. Το οινοποιείο διαθέτει σύγχρονο εξοπλισμό και χώρους γευσιγνωσίας, ενώ η οικογένεια έχει διατηρήσει έναν άμεσο και προσωπικό χαρακτήρα στη φιλοξενία και την παρουσίαση των κρασιών της.",
  "Η παραγωγή δεν περιορίζεται στις κλασικές ποικιλίες της Κρήτης. Δίπλα στο Κοτσιφάλι, το Βιδιανό και άλλες τοπικές ποικιλίες βρίσκονται διεθνείς ποικιλίες, αλλά και σπάνιες ποικιλίες από διαφορετικές περιοχές του κόσμου. Αυτή η συνύπαρξη παράδοσης και πειραματισμού αποτελεί βασικό στοιχείο της σύγχρονης ταυτότητας της Karavitakis Winery.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία της Karavitakis Winery βασίζεται στην ιδέα ότι η διαφορετικότητα του αμπελώνα μπορεί να οδηγήσει σε κρασιά με μεγαλύτερη πολυπλοκότητα και σαφή ταυτότητα. Για τον λόγο αυτό, τα αμπελοτόπια επιλέγονται με βάση την καταλληλότητά τους για κάθε ποικιλία, ενώ η οικογένεια καλλιεργεί τόσο γηγενείς κρητικές όσο και διεθνείς ποικιλίες.",
  "Το κτήμα διατηρεί παράλληλα έναν έντονο πειραματικό χαρακτήρα. Εκτός από τις καθιερωμένες ποικιλίες, η οικογένεια δοκιμάζει και σπάνιες ποικιλίες από διαφορετικά μέρη του κόσμου, αναζητώντας νέες εκφράσεις μέσα στο κρητικό περιβάλλον. Η προσέγγιση αυτή αποτυπώνεται σε διαφορετικά στυλ κρασιών, από το μονοποικιλιακό Vidiano του Klima White έως blends όπως το Elia Blend με Syrah, Grenache και Carignan.",
  "Η οινοποίηση ακολουθεί σύγχρονες τεχνικές, με διαφορετικές επιλογές ανάλογα με τον χαρακτήρα κάθε κρασιού. Η χρήση δεξαμενών και, όπου απαιτείται, βαρελιού επιτρέπει στην ομάδα να διαμορφώνει διαφορετικές εκφράσεις χωρίς να απομακρύνεται από την πρώτη ύλη.",
  "Στον πυρήνα παραμένει η σχέση ποικιλίας και τόπου: η Κρήτη λειτουργεί ως σημείο αναφοράς, αλλά όχι ως περιορισμός. Η Karavitakis Winery αντιμετωπίζει τον αμπελώνα ως πεδίο συνεχούς εξερεύνησης, συνδυάζοντας την οικογενειακή παράδοση με τη διάθεση για νέες ποικιλίες και διαφορετικές οινοποιητικές κατευθύνσεις.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "karavitakis" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
