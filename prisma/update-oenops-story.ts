import { prisma } from "../lib/prisma";

const story = [
  "Η Oenops Wines γεννήθηκε από την επιθυμία να αναδείξει την αυθεντική έκφραση του ελληνικού αμπελώνα μέσα από τις γηγενείς ποικιλίες και τη μοναδικότητα κάθε τόπου. Χωρίς ιδιόκτητα αμπέλια, συνεργάζεται με επιλεγμένους αμπελουργούς σε όλη την Ελλάδα, δημιουργώντας σχέσεις βασισμένες στον σεβασμό, την εμπιστοσύνη και την κοινή αγάπη για τη γη.",
  "Στο οινοποιείο, κάθε αμπελώνας αντιμετωπίζεται ξεχωριστά, με σύγχρονες και ήπιες μεθόδους οινοποίησης που επιτρέπουν στο σταφύλι, το έδαφος και τη σοδειά να εκφραστούν με καθαρότητα. Χωρίς περιττές παρεμβάσεις και χωρίς να καλύπτεται ο χαρακτήρας του κρασιού, στόχος είναι η δημιουργία κρασιών ζωντανών, ισορροπημένων και κομψών.",
  "Πίσω από την Oenops Wines βρίσκεται ο Νίκος Καρατζάς, με βαθιά γνώση και πολυετή εμπειρία στον χώρο του κρασιού. Το όραμά του είναι να αναδείξει τη δυναμική των ελληνικών ποικιλιών και να δημιουργήσει κρασιά που αποτυπώνουν με ειλικρίνεια τον τόπο, τον χρόνο και την προσωπικότητά τους.",
  "Η Oenops Wines είναι μια σύγχρονη ματιά στο ελληνικό κρασί — με βαθιές ρίζες στην παράδοση και απόλυτη προσήλωση στην αυθεντικότητα.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "oenops-wines" },
    data: { story },
  });
  console.log(`✓ ${winery.name} -> story updated (${story.length} chars)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
