async function main() {
  console.log("Seeding νέα άρθρα…");
  for (const a of articles) {
    const { slug, daysAgo, ...data } = a;
    const publishedAt = new Date(Date.now() - daysAgo * 24 * 60 * 60 * 1000);
    await prisma.article.upsert({
      where: { slug },
      update: { ...data, status: ContentStatus.PUBLISHED, publishedAt },
      create: { slug, ...data, status: ContentStatus.PUBLISHED, publishedAt },
    });
  }
  console.log(`Done: ${articles.length} άρθρα.`);
}

main()
