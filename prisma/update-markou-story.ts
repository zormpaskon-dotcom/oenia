// Κείμενο story για τους Αμπελώνες Μάρκου, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στην Αττική, οι Αμπελώνες Μάρκου μεταφέρουν μια οικογενειακή οινοποιητική παράδοση που συνεχίζεται αδιάκοπα από το 1908 και σήμερα βρίσκεται στα χέρια της τέταρτης γενιάς. Η οικογένεια ασχολείται εδώ και αιώνες με την αμπελουργία στα Μεσόγεια και τη Λαυρεωτική, ενώ στις αρχές του 20ού αιώνα πέρασε από την καλλιέργεια στην οργανωμένη παραγωγή και εμπορία κρασιού.",
  "Το Σαββατιανό βρίσκεται στον πυρήνα αυτής της ιστορίας. Οι αμπελώνες της οικογένειας περιλαμβάνουν παλιά, κυπελλοειδή και κυρίως ξηρικά κλήματα ηλικίας άνω των 65 ετών, τόσο στην Αττική όσο και στη ζώνη της Νεμέας. Το 1983 δημιουργήθηκε η σύγχρονη οινοποιητική μονάδα της οικογένειας, ενώ το 1998 η παρουσία της επεκτάθηκε στη Νεμέα με την προσθήκη του Αγιωργίτικου.",
  "Σήμερα, οι Αμπελώνες Μάρκου συνδυάζουν την προφορική παράδοση του Αττικού αμπελώνα με τη σύγχρονη οινολογική γνώση, διατηρώντας χώρο για πειραματισμό και εξέλιξη. Παράλληλα, το Μουσείο Οίνου της οικογένειας λειτουργεί ως σημείο αναφοράς για την ιστορία και την οινοποιητική κληρονομιά της Αττικής.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "markou-vineyards" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
