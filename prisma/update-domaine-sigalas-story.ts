// Κείμενο story για το Domaine Sigalas, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στον κάμπο της Οίας, στη βόρεια Σαντορίνη, το Domaine Sigalas έχει συνδέσει το όνομά του με τη σύγχρονη εξέλιξη του σαντορινιού κρασιού και ιδιαίτερα με την ανάδειξη του Ασύρτικου. Ιδρυτής του είναι ο Παρίσης Σιγάλας, με καταγωγή από οικογένεια με μακρά οινοποιητική παράδοση, ο οποίος δημιούργησε την πρώτη του ετικέτα το 1991.",
  "Κεντρική ιδέα της φιλοσοφίας του είναι η «δυναμική εξέλιξη της παράδοσης»: η αρχαία αμπελουργική κληρονομιά της Σαντορίνης συναντά τη σύγχρονη τεχνογνωσία και τον πειραματισμό, με στόχο την όσο το δυνατόν ακριβέστερη έκφραση του ηφαιστειακού terroir του νησιού.",
  "Το Domaine διαθέτει περίπου 40 εκτάρια αμπελώνων γύρω από το οινοποιείο, οι οποίοι καλλιεργούνται με βιώσιμες πρακτικές. Το Ασύρτικο βρίσκεται στο επίκεντρο, πλαισιωμένο από τις υπόλοιπες παραδοσιακές ποικιλίες της Σαντορίνης και των Κυκλάδων. Στον αμπελώνα και στο οινοποιείο, η παράδοση δεν αντιμετωπίζεται ως στατική κληρονομιά, αλλά ως βάση για συνεχή εξέλιξη.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "domaine-sigalas" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
