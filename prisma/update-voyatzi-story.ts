// Κείμενο story για το Κτήμα Βογιατζή, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στο Βελβεντό Κοζάνης, στις όχθες της λίμνης Πολυφύτου, το Κτήμα Βογιατζή αποτελεί μια σύγχρονη έκφραση της μακράς οινικής παράδοσης της οικογένειας. Η σχέση των Βογιατζήδων με το κρασί καταγράφεται ήδη από τις αρχές του 20ού αιώνα, όταν η οικογένεια δραστηριοποιούνταν στο εμπόριο κρασιών και τσίπουρου. Το 1997, ο οινολόγος Γιάννης Βογιατζής, μαζί με τον αδελφό του Νίκο και τον πατέρα τους Χαρίση, επέστρεψαν στο Βελβεντό για να δημιουργήσουν τον δικό τους αμπελώνα.",
  "Ο αμπελώνας αναπτύχθηκε σταδιακά και σήμερα εκτείνεται σε περίπου 12 εκτάρια, με έμφαση στις ελληνικές γηγενείς ποικιλίες και ιδιαίτερα στο Ξινόμαυρο και τον Τσαπουρνάκο. Παράλληλα καλλιεργούνται ποικιλίες όπως το Μοσχόμαυρο και το Ασύρτικο, ενώ το portfolio συμπληρώνεται από διεθνείς ποικιλίες.",
  "Η προσέγγιση του Κτήματος συνδυάζει την οικογενειακή εμπειρία με την επιστημονική γνώση και τη σύγχρονη οινοποίηση. Η ιδέα είναι να αποτυπώνεται στο κρασί ο ιδιαίτερος χαρακτήρας του Βελβεντού, μέσα από τις ποικιλίες, το τοπικό μικροκλίμα και τη φροντίδα του αμπελώνα. Το σύγχρονο οινοποιείο ολοκληρώθηκε το 2004 και σήμερα λειτουργεί παράλληλα ως επισκέψιμος χώρος, προσφέροντας ξεναγήσεις και γευστικές δοκιμές.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "voyatzi-winery" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
