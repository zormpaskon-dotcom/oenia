// Κείμενο story για το Domaine Hatzimichalis, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στην Κοιλάδα της Αταλάντης, στη Φθιώτιδα, το Κτήμα Χατζημιχάλη αποτελεί μια οικογενειακή οινοποιητική ιστορία που ξεκίνησε το 1973, όταν ο Δημήτρης Χατζημιχάλης απέκτησε τα πρώτα 90 στρέμματα αμπελώνα. Από νεαρή ηλικία είχε ήδη στραφεί στην οινοποίηση, δημιουργώντας τα πρώτα του κρασιά και μελετώντας συστηματικά την ιστορία και την τέχνη του κρασιού.",
  "Η επιλογή της Κοιλάδας της Αταλάντης βασίστηκε στη μελέτη του τόπου και των καταλληλότερων ποικιλιών για την περιοχή. Με τα χρόνια, το κτήμα εξελίχθηκε σε μια μεγάλη οικογενειακή αμπελουργική επιχείρηση, που σήμερα διαθέτει περίπου 2.200 στρέμματα ιδιόκτητων αμπελώνων και διοικείται από τον ιδρυτή μαζί με τους δύο γιους του.",
  "Η φιλοσοφία του κτήματος βασίζεται στον σεβασμό προς τη φύση και τον άνθρωπο, ενώ η πορεία του συνδέεται με την προσπάθεια ανάδειξης τόσο διεθνών όσο και ελληνικών ποικιλιών. Από τα πρώτα Cabernet Sauvignon έως τη συνύπαρξη Ασύρτικου και Ρομπόλας, η ιστορία του Κτήματος Χατζημιχάλη χαρακτηρίζεται από συνεχή εξέλιξη και αναζήτηση ποιότητας.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "domaine-hatzimichalis" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
