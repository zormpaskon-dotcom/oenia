// Κείμενο story για το Petrakopoulos Wines, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στη Θηράμονα της νότιας Κεφαλονιάς, το Petrakopoulos Wines αποτελεί ένα μικρό οικογενειακό οινοποιητικό εγχείρημα που ξεκίνησε επίσημα το 2002, με επικεφαλής τον Νίκο Πετρακόπουλο. Η φιλοσοφία του βασίζεται στη διατήρηση και ανάδειξη του πλούτου του κεφαλονίτικου αμπελώνα, με ιδιαίτερη έμφαση στις σπάνιες τοπικές ποικιλίες και στα παλιά, προφυλλοξηρικά αμπέλια.",
  "Η καλλιέργεια ακολουθεί βιολογική προσέγγιση και οι παρεμβάσεις στην οινοποίηση παραμένουν περιορισμένες, ώστε τα κρασιά να διατηρούν την ιδιαίτερη ταυτότητα του τόπου. Ανάμεσα στις ποικιλίες που βρίσκονται στο επίκεντρο είναι το Ζακυνθινό, το Βοστυλίδι και η Μαυροδάφνη, ενώ η συλλογή περιλαμβάνει τόσο λευκές όσο και ερυθρές εκφράσεις.",
  "Ιδιαίτερο ενδιαφέρον παρουσιάζουν οι παλιοί ξηρικοί αμπελώνες της νότιας Κεφαλονιάς. Σε χαρακτηριστικό αμπελώνα Ζακυνθινού, τα κλήματα βρίσκονται περίπου στα 350 μέτρα και καλλιεργούνται παραδοσιακά σε κύπελλο, με πολύ χαμηλές αποδόσεις. Η οινοποίηση μικρής κλίμακας και οι περιορισμένες εμφιαλώσεις αποτελούν μέρος της ίδιας λογικής: κρασιά που λειτουργούν ως αυθεντικές εκφράσεις του κεφαλονίτικου terroir.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "petrakopoulos-wines" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
