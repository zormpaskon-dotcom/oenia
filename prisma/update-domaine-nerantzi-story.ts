// Κείμενο story για το Domaine Nerantzi, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στην Πεντάπολη των Σερρών, το Domaine Nerantzi αποτελεί μια οικογενειακή οινοποιητική διαδρομή που ξεκίνησε το 1988, με αφετηρία την επιθυμία να διατηρηθεί η τοπική παράδοση και να μεταφραστεί σε σύγχρονο κρασί. Το πρώτο οινοποιείο δημιουργήθηκε το 1998 στην περιοχή Επτάμυλοι, ενώ τα επόμενα χρόνια η οικογένεια επέκτεινε τη δραστηριότητά της στους ιστορικούς αμπελώνες της Πεντάπολης.",
  "Ιδιαίτερη θέση στην ιστορία του κτήματος έχει η προσπάθεια διάσωσης και επίσημης αναγνώρισης δύο γηγενών ποικιλιών των Σερρών, της Ασπρούδας Σερρών και του Κόνιαρου. Η σχέση με τον τόπο δεν περιορίζεται στις ποικιλίες, αλλά εκφράζεται μέσα από ένα αμπελοτόπι που περιβάλλεται από πέντε ορεινούς όγκους και εκτείνεται στην κοιλάδα του Στρυμόνα.",
  "Σήμερα, το κτήμα διαθέτει περίπου 20 εκτάρια γης, από τα οποία 10,8 εκτάρια είναι αμπελώνες, ενώ η οικογενειακή φιλοσοφία συνδυάζει την παράδοση με τη σύγχρονη οινοποίηση και την οργανική καλλιέργεια. Το οινοποιείο λειτουργεί παράλληλα ως χώρος γευσιγνωσίας και φιλοξενίας, συνδέοντας το κρασί με την ιστορία και το τοπίο των Σερρών.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "domaine-nerantzi" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
