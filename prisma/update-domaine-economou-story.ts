// Κείμενο story για το Domaine Economou, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στο οροπέδιο της Ζήρου, στη Σητεία της ανατολικής Κρήτης, το Domaine Economou αποτελεί ένα από τα πιο προσωπικά οινοποιητικά εγχειρήματα του Γιάννη Οικονόμου. Μετά από σπουδές οινολογίας και εμπειρία σε σημαντικές οινοποιητικές περιοχές της Ευρώπης, ο Οικονόμου επέστρεψε στην Κρήτη το 1994, στρέφοντας την προσοχή του στους παλιούς οικογενειακούς αμπελώνες και στις γηγενείς ποικιλίες του τόπου.",
  "Οι αμπελώνες του κτήματος εκτείνονται σε περίπου 16 εκτάρια, στα χωριά Ζήρος, Κατσιδόνι και Ετιά, σε υψόμετρο 600–650 μέτρων. Πρόκειται για ένα ιδιαίτερα ορεινό και εκτεθειμένο περιβάλλον, με παλιές, αυτόριζες φυτεύσεις και καλλιέργεια με σεβασμό στις αρχές της οργανικής γεωργίας.",
  "Στο επίκεντρο βρίσκονται το Λιάτικο, η Μανδηλαριά, η Βηλάνα και το Θραψαθήρι, ποικιλίες που εκφράζουν την ιδιαίτερη φυσιογνωμία της Σητείας. Η οινοποίηση χαρακτηρίζεται από χαμηλές παρεμβάσεις και μακρά ωρίμαση, αφήνοντας τον χρόνο, την ποικιλία και το υψόμετρο να διαμορφώσουν τον χαρακτήρα των κρασιών.",
  "Το Domaine Economou δεν επιδιώκει την ομοιομορφία· αναζητά την αυθεντική έκφραση ενός συγκεκριμένου τόπου της Κρήτης.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "domaine-economou" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
