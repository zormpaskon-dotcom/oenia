// Κείμενο story για το Rouvalis Winery, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στις πλαγιές της Αιγιάλειας, με θέα στον Κορινθιακό κόλπο, το Οινοποιείο Ρούβαλη αποτελεί μία από τις χαρακτηριστικές οινοποιητικές παρουσίες της ορεινής Πελοποννήσου. Η ιστορία του ξεκίνησε το 1990, όταν ο οινολόγος Άγγελος Ρούβαλης δημιούργησε στην περιοχή ένα πρωτοποριακό οινοποιείο, έχοντας ως στόχο να αναδείξει το δυναμικό του ορεινού Ροδίτη και γενικότερα της Αιγιάλειας.",
  "Το 1994 ολοκληρώθηκε το πρότυπο βαρυτικό οινοποιείο, χτισμένο πάνω στον βράχο σε έξι διαδοχικά επίπεδα. Η φυσική ροή της βαρύτητας χρησιμοποιείται σε όλα τα στάδια της παραγωγής, περιορίζοντας την ανάγκη για αντλήσεις και αποτελώντας βασικό στοιχείο της οινοποιητικής ταυτότητας του κτήματος.",
  "Στους αμπελώνες καλλιεργούνται Ροδίτης, Λαγόρθι, Κυδωνίτσα, Ασύρτικο και Μαυροδάφνη Τσιγκέλω, μαζί με Riesling, Chardonnay και Cabernet Franc. Από το 2017, η Θεοδώρα Ρούβαλη και ο Antonio Ruiz Pañego συνδυάζουν τη διεθνή τους εμπειρία με έμφαση στη βιολογική καλλιέργεια, την αμπελουργία ακριβείας και την όσο το δυνατόν καθαρότερη έκφραση του ιδιαίτερου terroir της Αιγιάλειας.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "rouvalis-winery" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
