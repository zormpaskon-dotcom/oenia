// Κείμενο story + philosophy για το Santo Wines, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Η ιστορία της Santo Wines είναι άμεσα συνδεδεμένη με την ιστορία της σύγχρονης αμπελουργίας της Σαντορίνης. Οι ρίζες της φτάνουν στο 1911, όταν ιδρύθηκε το Ταμείο Αμύνης Οινοπαραγωγής Θήρας, με σκοπό την προστασία της αμπελουργικής παραγωγής του νησιού. Το 1947 μετατράπηκε σε Ένωση Συνεταιρισμών Θηραϊκών Προϊόντων, από την οποία προέκυψε η σημερινή Santo Wines.",
  "Το 1985 εμφιαλώθηκε το πρώτο κρασί ΠΟΠ Σαντορίνη με την επωνυμία Santo Wines, ενώ το 1993 ολοκληρώθηκε το σύγχρονο οινοποιείο στον Πύργο, μαζί με το Κέντρο Προβολής Οίνων Σαντορίνης. Η θέση του, πάνω από την Καλντέρα, έγινε σταδιακά σημείο αναφοράς για τον οινοτουρισμό του νησιού.",
  "Σήμερα, η Santo Wines εκπροσωπεί περίπου 1.200 ενεργά μέλη-αμπελουργούς και αποτελεί έναν από τους μεγαλύτερους οργανισμούς της Σαντορίνης. Η παραγωγή κρασιού συνυπάρχει με την επεξεργασία τοπικών αγροτικών προϊόντων, όπως η φάβα και το τοματάκι Σαντορίνης. Η πορεία της Santo Wines είναι επομένως άρρηκτα συνδεδεμένη όχι μόνο με το κρασί, αλλά και με την προστασία της αγροτικής κληρονομιάς και της παραγωγικής κοινότητας του νησιού.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία της Santo Wines βασίζεται σε τέσσερις έννοιες που η ίδια η συνεταιριστική οργάνωση θέτει στο επίκεντρο: συλλογικότητα, ποιότητα, αυθεντικότητα και βιώσιμη ανάπτυξη. Πίσω από κάθε κρασί βρίσκεται το δίκτυο των περίπου 1.200 ενεργών μελών-παραγωγών, με βασικό στόχο την προστασία της τοπικής αμπελουργίας και τη διασφάλιση δίκαιων όρων για τους καλλιεργητές.",
  "Η Santo Wines επενδύει παράλληλα στην έρευνα και στην εξέλιξη των πρακτικών καλλιέργειας και οινοποίησης. Διατηρεί φυτώριο γηγενών ποικιλιών για μελέτη και δοκιμαστικές φυτεύσεις, ενώ διαθέτει και ιδιόκτητο βιολογικό αμπελώνα 0,2 εκταρίων, από τον οποίο παράγονται μονοποικιλιακά κρασιά από Αηδάνι, Αθηρί και Μαυροτράγανο.",
  "Στο οινοποιείο, η αρχιτεκτονική ακολουθεί την τοπογραφία του νησιού. Η εγκατάσταση στον Πύργο είναι διαμορφωμένη σε επίπεδα, αντίστοιχα με τις αναβαθμίδες του σαντορινιού αμπελώνα, ενώ η μεταφορά του μούστου και του κρασιού πραγματοποιείται με τη βοήθεια της βαρύτητας, περιορίζοντας την ανάγκη για αντλίες.",
  "Η Santo Wines αντιμετωπίζει επομένως το κρασί ως συλλογικό προϊόν του τόπου: αποτέλεσμα της ηφαιστειακής γης, των τοπικών ποικιλιών και κυρίως των ανθρώπων που συνεχίζουν να καλλιεργούν τη Σαντορίνη.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "santo-wines" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
