  "Η σύγχρονη πορεία του οινοποιείου ξεκινά το 2003, όταν ο Αρτέμης Καραμολέγκος δημιουργεί το πρώτο του κρασί στις νέες εγκαταστάσεις στην Έξω Γωνιά. Από τότε, η προσπάθεια επικεντρώνεται στην κατανόηση και την ανάδειξη του σαντορινιού αμπελώνα, με το Ασύρτικο να αποτελεί σταθερό σημείο αναφοράς.",
