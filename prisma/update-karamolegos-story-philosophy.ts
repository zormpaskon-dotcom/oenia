  "Στον αμπελώνα, η παραδοσιακή καλλιέργεια με «κουλούρα» προστατεύει τα σταφύλια από τους ισχυρούς ανέμους, ενώ η προσεκτική επιλογή και ο διαχωρισμός των σταφυλιών επιτρέπουν την πιο καθαρή αποτύπωση κάθε τόπου.",
