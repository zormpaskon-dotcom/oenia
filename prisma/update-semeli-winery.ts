// Ενημέρωση Semeli Estate — ιστορία (story) που έστειλε ο χρήστης από το
// ίδιο το οινοποιείο, και έτος ίδρυσης (1979, επιβεβαιωμένο και από το
// "EST. 1979" σε κάθε ετικέτα του κτήματος).

import { prisma } from "../lib/prisma";

const STORY = `Από το 1979, το Κτήμα ΣΕΜΕΛΗ αποτελεί μια ξεχωριστή παρουσία στον ελληνικό αμπελώνα, έχοντας συνδέσει την ιστορία του με τη γη της Νεμέας και τη διαρκή αναζήτηση της ποιότητας.

Στις πλαγιές του Κουτσίου Κορινθίας, σε υψόμετρο 600 μέτρων, το αμπέλι συναντά ένα μοναδικό terroir. Το υψόμετρο, το μεσογειακό κλίμα και το ιδιαίτερο μικροκλίμα της περιοχής δημιουργούν συνθήκες που ευνοούν τη βαθιά έκφραση του καρπού, με χαμηλές αποδόσεις και φυσική ισορροπία ανάμεσα στην ένταση, την οξύτητα και την ωριμότητα.

Στην καρδιά του κτήματος βρίσκεται ένας ιδιόκτητος αμπελώνας 250 στρεμμάτων, πλαισιωμένος από επιλεγμένα αμπελοτόπια της ευρύτερης Νεμέας. Κάθε αμπέλι καλλιεργείται με συνέπεια και προσοχή, με τη γνώση και την εμπειρία της ομάδας να λειτουργούν ως γέφυρα ανάμεσα στη γη και στο κρασί.

Η φιλοσοφία της ΣΕΜΕΛΗ βασίζεται στην ανάδειξη του χαρακτήρα του τόπου. Ελληνικές και διεθνείς ποικιλίες βρίσκουν εδώ τη δική τους έκφραση, δημιουργώντας κρασιά που ισορροπούν ανάμεσα στην αυθεντικότητα και τη σύγχρονη οινοποιητική αισθητική.

Με βαθιές ρίζες στην ελληνική παράδοση και σταθερό προσανατολισμό προς το μέλλον, το Κτήμα ΣΕΜΕΛΗ συνεχίζει να εξελίσσεται, μεταφέροντας την ποιότητα και την ταυτότητα της Νεμέας σε ένα ολοένα και μεγαλύτερο διεθνές κοινό.`;

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "semeli-estate" },
    data: {
      story: STORY,
      foundedYear: 1979,
    },
  });
  console.log(`✓ Ενημερώθηκε: ${winery.name} (foundedYear=${winery.foundedYear}, story: ${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
