// Κείμενο story + philosophy για το Moraitis Winery, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στη Νάουσα της Πάρου, δίπλα στην παραλία των Αγίων Αναργύρων, το Οινοποιείο Μωραΐτη αποτελεί μία από τις ιστορικότερες οικογενειακές οινοποιητικές παρουσίες του νησιού. Η ιστορία ξεκινά το 1910, όταν ο Μανώλης Μωραΐτης καλλιεργούσε τα δικά του αμπέλια και παράλληλα συγκέντρωνε σταφύλια από επιλεγμένα αμπελοτόπια της Πάρου. Τα κρασιά ταξίδευαν με το οικογενειακό πλοίο σε διάφορα λιμάνια του Αιγαίου, συνδέοντας από νωρίς το οινοποιείο με το εμπορικό δίκτυο της εποχής.",
  "Η δεύτερη γενιά συνέχισε την αμπελουργία και την οινοποίηση, ενώ το 1967 ξεκίνησε η εμφιάλωση. Το 1980 ανέλαβε η τρίτη γενιά, εκσυγχρονίζοντας τις εγκαταστάσεις και επεκτείνοντας τους αμπελώνες με ελληνικές και ξένες ποικιλίες.",
  "Σήμερα, η τέταρτη γενιά συνεχίζει την οικογενειακή πορεία, με ιδιόκτητους αμπελώνες περίπου 10 εκταρίων και παραγωγή που επικεντρώνεται στις γηγενείς ποικιλίες της Πάρου. Το οινοποιείο διατηρεί επίσης υπόγειες κάβες παλαίωσης, μουσείο οίνου και χώρο γευσιγνωσίας, συνδέοντας την παραγωγή με την ιστορία του παριανού αμπελώνα.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία του Οινοποιείου Μωραΐτη ξεκινά από την προστασία και την ανάδειξη του ιστορικού αμπελώνα της Πάρου. Η οικογένεια δίνει ιδιαίτερη έμφαση στις γηγενείς ποικιλίες του νησιού, με τη Μονεμβασιά και τη Μανδηλαριά να αποτελούν βασικούς πυλώνες της παραγωγής, ενώ παράλληλα καλλιεργούνται Αηδάνι Μαύρο, Βάφτρα και Καραμπραήμι.",
  "Οι ιδιόκτητοι αμπελώνες καλλιεργούνται με βιολογικές πρακτικές και βρίσκονται σε διαφορετικά σημεία της Πάρου, από παράκτιες έως ορεινότερες θέσεις. Το ξηρό έδαφος, οι περιορισμένες βροχοπτώσεις, οι ισχυροί άνεμοι και οι παραδοσιακές μορφές καλλιέργειας διαμορφώνουν ένα ιδιαίτερο περιβάλλον, στο οποίο το αμπέλι έχει προσαρμοστεί εδώ και αιώνες.",
  "Στο οινοποιείο, η παραδοσιακή γνώση συνδυάζεται με σύγχρονες τεχνικές και διαφορετικές μεθόδους οινοποίησης. Ανοξείδωτες δεξαμενές, δρύινα βαρέλια, τσιμέντο και αμφορείς χρησιμοποιούνται ανάλογα με τον χαρακτήρα κάθε κρασιού. Η Μονεμβασιά αποκτά ιδιαίτερη θέση μέσα από διαφορετικές εκφράσεις, από φρέσκα λευκά έως παλαιωμένες και γλυκές εμφιαλώσεις.",
  "Στόχος παραμένει η διατήρηση του χαρακτήρα των παριανών αμπελώνων και η ανάδειξη της ποιότητας των τοπικών ποικιλιών, σε μια εποχή όπου ο ιστορικός αμπελώνας της Πάρου αντιμετωπίζει αυξανόμενες πιέσεις από την τουριστική ανάπτυξη.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "moraitis-winery" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
