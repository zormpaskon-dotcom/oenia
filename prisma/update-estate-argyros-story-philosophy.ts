// Κείμενο story + philosophy για το Estate Argyros, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στην Επισκοπή Γωνιά της Σαντορίνης, η οικογένεια Αργυρού συνδέεται με την αμπελουργία και την παραγωγή κρασιού εδώ και αιώνες. Η ενασχόληση της οικογένειας με τον αμπελώνα ξεκινά ήδη από τον 18ο αιώνα, ενώ το Estate Argyros ιδρύθηκε επίσημα το 1903 από τον Γεώργιο Αργυρό.",
  "Καθοριστική μορφή στην εξέλιξη του κτήματος υπήρξε ο Γιάννης Αργυρός, ο οποίος ανέλαβε το 1974 και αφιέρωσε περισσότερες από τρεις δεκαετίες στην ανάδειξη τόσο του Vinsanto όσο και του Ασύρτικου της Σαντορίνης ως κρασιών με σημαντικές δυνατότητες ποιότητας και παλαίωσης.",
  "Από το 2004, την τέταρτη γενιά εκπροσωπεί ο Ματθαίος Αργυρός. Υπό τη δική του καθοδήγηση, το κτήμα επένδυσε σημαντικά στην επέκταση των αμπελώνων και στη δημιουργία ενός σύγχρονου οινοποιείου στην Επισκοπή, το οποίο ολοκληρώθηκε το 2015.",
  "Σήμερα, το Estate Argyros διαθέτει περισσότερα από 120 εκτάρια αμπελώνων, με μέση ηλικία φυτών άνω των 70 ετών και ορισμένα αμπελοτεμάχια ηλικίας άνω των δύο αιώνων. Στο επίκεντρο παραμένουν οι γηγενείς ποικιλίες της Σαντορίνης, με το Ασύρτικο να αποτελεί τον βασικό άξονα της οινοποιητικής ταυτότητας του κτήματος.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία του Estate Argyros ξεκινά από τον παλιό αμπελώνα. Το κτήμα εργάζεται σχεδόν αποκλειστικά με παλιά αμπέλια, θεωρώντας ότι η ηλικία και η ισορροπία τους επιτρέπουν μεγαλύτερο βάθος, συμπύκνωση και σαφέστερη έκφραση του τόπου. Κάθε αμπελοτεμάχιο αντιμετωπίζεται ξεχωριστά και η ημερομηνία του τρύγου καθορίζεται με βάση την πραγματική ωριμότητα του καρπού.",
  "Στο οινοποιείο δεν υπάρχει μία ενιαία «συνταγή». Τα διαφορετικά αμπελοτεμάχια τρυγούνται, οινοποιούνται και ωριμάζουν ξεχωριστά για μεγάλο μέρος της διαδικασίας, ώστε κάθε κρασί να διατηρεί την ταυτότητα της προέλευσής του. Η χρήση παλιών και μεγάλων γαλλικών βαρελιών λειτουργεί συμπληρωματικά, με στόχο να υπογραμμίζει τον χαρακτήρα του κρασιού και όχι να τον δημιουργεί.",
  "Στον αμπελώνα εφαρμόζονται οργανικές πρακτικές χωρίς φυτοφάρμακα, οι εργασίες γίνονται χειρωνακτικά και τα αμπέλια δεν αρδεύονται. Η παραδοσιακή «κουλούρα» και, σε επιλεγμένες θέσεις, η «κουλούρι» αποτελούν προσαρμογές στις ιδιαίτερες συνθήκες της Σαντορίνης, προστατεύοντας τα φυτά από τους ισχυρούς ανέμους και βοηθώντας στη διαχείριση της υγρασίας.",
  "Στο επίκεντρο βρίσκονται το Ασύρτικο, το Αηδάνι και το Μαυροτράγανο, ποικιλίες που αποτελούν μέρος της αμπελουργικής κληρονομιάς της Σαντορίνης. Η συνολική προσέγγιση του κτήματος δίνει έμφαση στην καθαρότητα, την ακρίβεια και κυρίως στη δυνατότητα των κρασιών να εξελίσσονται στον χρόνο.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "estate-argyros" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
