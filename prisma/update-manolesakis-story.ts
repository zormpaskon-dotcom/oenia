// Κείμενο story για το Estate Manolesakis, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στην Αδριανή της Δράμας, το Κτήμα Μανωλεσάκη αποτελεί μια οικογενειακή οινοποιητική προσπάθεια με παρουσία από το 1989. Ο Γιώργος Μανωλεσάκης ήταν από τους ανθρώπους που συνέβαλαν στην αναβίωση της αμπελουργίας στην περιοχή, ενώ σήμερα ο γιος του Σταύρος συνεχίζει την οικογενειακή δραστηριότητα, έχοντας προσωπική παρουσία στην καλλιέργεια και την παραγωγή.",
  "Το οινοποιείο ολοκληρώθηκε το 1998 και βρίσκεται στην καρδιά ιδιόκτητου αμπελώνα 200 στρεμμάτων, σε υψόμετρο 200–300 μέτρων. Τα αργιλοπηλώδη εδάφη, η βορειοδυτική έκθεση και το ημι-ηπειρωτικό κλίμα δημιουργούν τις συνθήκες για αμπέλια με έντονο αρωματικό και δομικό χαρακτήρα.",
  "Στον αμπελώνα συνυπάρχουν διεθνείς ποικιλίες όπως Sauvignon Blanc, Chardonnay, Cabernet Sauvignon, Merlot και Syrah με ελληνικές, όπως Μαλαγουζιά, Ασύρτικο, Αγιωργίτικο, Λημνιό και Μοσχόμαυρο. Στόχος παραμένει η παραγωγή κρασιών αποκλειστικά από τον ιδιόκτητο αμπελώνα, με έμφαση στην έκφραση της κάθε ποικιλίας και του terroir της Δράμας.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "manolesakis-estate" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
