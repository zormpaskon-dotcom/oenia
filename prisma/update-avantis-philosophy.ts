// Κείμενο philosophy για το Avantis Estate, δόθηκε αυτούσιο από τον χρήστη.
// Το υπάρχον story παραμένει άθικτο.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const PHILOSOPHY = [
  "Η φιλοσοφία του Κτήματος Avantis βασίζεται στην αναζήτηση της ισορροπίας ανάμεσα στον χαρακτήρα του αμπελώνα, την ποικιλία και τη σύγχρονη οινοποιητική γνώση. Στο επίκεντρο βρίσκεται η Εύβοια και η δυνατότητα διαφορετικών αμπελοτοπιών να εκφράσουν τον δικό τους χαρακτήρα μέσα από το κρασί.",
  "Ιδιαίτερη θέση έχουν τόσο οι ελληνικές ποικιλίες, όπως η Μαλαγουζιά και το Ασύρτικο, όσο και το Syrah, με το οποίο το οινοποιείο έχει συνδέσει μεγάλο μέρος της σύγχρονης ταυτότητάς του. Η προσέγγιση δεν περιορίζεται σε μία μόνο οινοποιητική κατεύθυνση: διαφορετικές ποικιλίες, αμπελώνες και τρόποι ωρίμανσης χρησιμοποιούνται ώστε κάθε κρασί να αποκτά τη δική του ξεχωριστή έκφραση.",
  "Στα πιο εμβληματικά κρασιά του κτήματος, η επιλογή χαμηλών αποδόσεων, αυστηρής επιλογής σταφυλιών και προσεκτικής ωρίμανσης δείχνει την επιδίωξη για μεγαλύτερη συμπύκνωση και βάθος. Παράλληλα, η παραγωγή παραμένει συνδεδεμένη με την καθαρότητα του φρούτου και την αναγνωρισιμότητα της ποικιλίας.",
  "Για την Avantis, η σύγχρονη τεχνολογία λειτουργεί ως εργαλείο και όχι ως αυτοσκοπός: ο στόχος είναι το κρασί να διατηρεί την προσωπικότητα του αμπελώνα και να αποτυπώνει με σαφήνεια τον τόπο από τον οποίο προέρχεται.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "avantis-estate" },
    data: { philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: philosophy ενημερώθηκε (${PHILOSOPHY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
