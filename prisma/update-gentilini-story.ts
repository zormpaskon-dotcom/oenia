// Κείμενο story για το Gentilini Winery, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στην Κεφαλονιά, το Gentilini Winery & Vineyards αποτελεί ένα από τα ιστορικά boutique οινοποιεία του νησιού, με την πρώτη του ετικέτα να κυκλοφορεί το 1984. Η ιστορία του ξεκίνησε το 1978, όταν ο Σπύρος Κοσμετάτος επέστρεψε στην Κεφαλονιά και φύτεψε τα πρώτα του αμπέλια, αναζητώντας έναν τρόπο να αναδείξει τις ιδιαίτερες τοπικές ποικιλίες του νησιού.",
  "Σήμερα, τη δεύτερη γενιά εκπροσωπούν η Μαριάννα Κοσμετάτου και ο Πέτρος Μαρκαντονάτος, οι οποίοι ανέλαβαν το οινοποιείο το 2002. Οι αμπελώνες εκτείνονται σε περισσότερα από 10 εκτάρια και καλλιεργούνται με βιώσιμες πρακτικές, από τις περιοχές γύρω από τις Μηνιές έως τις πλαγιές του Αίνου.",
  "Στο επίκεντρο βρίσκονται οι γηγενείς ποικιλίες της Κεφαλονιάς, με τη Ρομπόλα, τη Μαυροδάφνη, το Τσαούσι και το Ζακυνθινό να ξεχωρίζουν, ενώ συμπληρώνονται από Μοσχοφίλερο και Syrah. Η συγκομιδή γίνεται χειρωνακτικά και η οινοποίηση πραγματοποιείται εξ ολοκλήρου στο κτήμα, με στόχο την καθαρή έκφραση της ποικιλίας και του κεφαλονίτικου terroir.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "gentilini" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
