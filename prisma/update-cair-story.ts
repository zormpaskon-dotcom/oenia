// Κείμενο story για το Cair Winery, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στη Ρόδο, η CAIR αποτελεί ένα από τα ιστορικότερα οινοποιητικά ονόματα της Ελλάδας, με ιστορία που ξεκινά το 1928, όταν ιδρύθηκε η Compagnia Agricola Industriale Rodi. Από τα πρώτα χρόνια της, η εταιρεία συνδέθηκε στενά με τον Ροδιακό αμπελώνα και εξελίχθηκε σε έναν από τους σημαντικούς φορείς της οινικής ιστορίας του νησιού.",
  "Ιδιαίτερη θέση στην πορεία της έχει η παραγωγή αφρωδών κρασιών με την παραδοσιακή μέθοδο, μια τεχνική που η CAIR εφαρμόζει εδώ και δεκαετίες. Παράλληλα, η δραστηριότητά της εκτείνεται σε λευκά, ερυθρά, ροζέ και γλυκά κρασιά, αξιοποιώντας τόσο γηγενείς όσο και διεθνείς ποικιλίες.",
  "Ο Ροδιακός αμπελώνας εκτείνεται κυρίως στις κεντρικές και δυτικές ορεινές περιοχές του νησιού, όπου το υψόμετρο, τα διαφορετικά εδάφη, ο προσανατολισμός και τα μικροκλίματα δημιουργούν ένα ιδιαίτερο αμπελουργικό περιβάλλον. Το Αθήρι και η Μανδηλαριά βρίσκονται στον πυρήνα της τοπικής οινικής παράδοσης, ενώ συνυπάρχουν με ποικιλίες όπως Μοσχάτο, Μαλαγουζιά, Ασύρτικο, Syrah, Cabernet Sauvignon, Merlot και Tempranillo.",
  "Σήμερα, η CAIR συνδυάζει την ιστορική της κληρονομιά με οργανικές και βιώσιμες πρακτικές, έχοντας ως βασικό στόχο την ανάδειξη του ιδιαίτερου terroir της Ρόδου μέσα από το κρασί.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "cair-winery" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
