// Κείμενο story για το Château Nico Lazaridi, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στη Δράμα, η Nico Lazaridi αποτελεί μια από τις οινοποιητικές επιχειρήσεις που συνέβαλαν καθοριστικά στη σύγχρονη αναγέννηση του τοπικού αμπελώνα. Η πορεία της ξεκίνησε το 1987, όταν ο Νίκος Λαζαρίδης, έχοντας ήδη αποκτήσει εμπειρίες από την Τοσκάνη και με βαθιά σχέση με τον τόπο καταγωγής του, δημιούργησε την πρώτη οργανωμένη οινοποιητική μονάδα της περιοχής.",
  "Το 1997 ιδρύθηκε το Château Nico Lazaridi στην Αγορά Δράμας, σε μια περιοχή που επιλέχθηκε για τη μορφολογία, το μικροκλίμα και την αμπελουργική της παράδοση. Σήμερα, οι αμπελώνες της περιοχής αποτελούν τη βάση για κρασιά με την ένδειξη ΠΓΕ Δράμα και Αγορά, ενώ από το 2000 η δραστηριότητα επεκτείνεται και στον Πλατανότοπο Καβάλας, στις παρυφές του Παγγαίου.",
  "Η Nico Lazaridi συνδυάζει ελληνικές και διεθνείς ποικιλίες, αναζητώντας διαφορετικές εκφράσεις του μακεδονικού terroir. Εμβληματικές σειρές όπως το Μαγικό Βουνό συνδέουν το κρασί με την τέχνη, μέσα από την περίφημη ομώνυμη πινακοθήκη του οινοποιείου. Παράλληλα, η συνεχής έρευνα στον αμπελώνα και ο πειραματισμός σε ποικιλίες και καλλιεργητικές πρακτικές αποτελούν βασικό μέρος της φιλοσοφίας του κτήματος.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "nico-lazaridi" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
