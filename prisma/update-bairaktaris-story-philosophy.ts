// Αντικατάσταση του γενικόλογου story + προσθήκη philosophy για το Ktima
// Bairaktaris, με πιο τεκμηριωμένο κείμενο που δόθηκε αυτούσιο από τον χρήστη
// (περιέχει συγκεκριμένες χρονολογίες — 1903, 1958 — που έλειπαν πριν).
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στη Νεμέα, η οικογένεια Μπαϊρακτάρη καλλιεργεί αμπέλια εδώ και τέσσερις γενιές. Η σχέση της με τον αμπελώνα ξεκινά ήδη από το 1903, όταν αποκτήθηκαν οι πρώτοι οικογενειακοί αμπελώνες στην περιοχή, ενώ το 1958 πραγματοποιήθηκαν οι πρώτες προσπάθειες οινοποίησης.",
  "Το 2005, ο Χρήστος Μπαϊρακτάρης αποφάσισε να δώσει σύγχρονη μορφή στην οικογενειακή παράδοση, ιδρύοντας το Κτήμα Μπαϊρακτάρης στη Νεμέα. Ακολούθησαν επεκτάσεις των εγκαταστάσεων το 2008 και το 2024, με στόχο την εξέλιξη της παραγωγικής διαδικασίας και του οινοποιητικού εξοπλισμού.",
  "Σήμερα, το οινοποιείο βρίσκεται στην είσοδο της Νεμέας, περιτριγυρισμένο από τον αμπελώνα του Αγιωργίτικου. Η παραγωγή φτάνει περίπου τις 250.000 φιάλες ετησίως, ενώ τα κρασιά ταξιδεύουν στην Ελλάδα, την Ευρωπαϊκή Ένωση και τις Ηνωμένες Πολιτείες.",
  "Το Αγιωργίτικο αποτελεί τον βασικό άξονα της παραγωγής, ενώ η γκάμα περιλαμβάνει και άλλες ελληνικές ποικιλίες, όπως Μαλαγουζιά και Ροδίτη. Η σύγχρονη πορεία του Κτήματος παραμένει συνδεδεμένη με τη Νεμέα και την οικογενειακή αμπελουργική κληρονομιά.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία του Κτήματος Μπαϊρακτάρης βασίζεται στη σχέση ανάμεσα στη γη της Νεμέας, τις ελληνικές ποικιλίες και τη σύγχρονη οινοποίηση. Το Αγιωργίτικο βρίσκεται στο επίκεντρο, με την οικογένεια να αντιμετωπίζει την ποικιλία ως βασικό μέσο έκφρασης του τόπου και της δικής της οινοποιητικής ταυτότητας.",
  "Στον αμπελώνα εφαρμόζεται Ολοκληρωμένο Σύστημα Διαχείρισης, ενώ η παραγωγή συνδυάζει σύγχρονο τεχνολογικό εξοπλισμό με πρακτικές που διατηρούν τη σύνδεση με την παράδοση. Η οικογένεια δίνει ιδιαίτερη έμφαση στη βιωσιμότητα και στη διατήρηση της ποιότητας της πρώτης ύλης, θεωρώντας ότι ένα καλό κρασί ξεκινά από υγιή και σωστά καλλιεργημένα σταφύλια.",
  "Στο οινοποιείο, η τεχνολογία χρησιμοποιείται με διαφορετικούς τρόπους ανάλογα με το κρασί. Η παραγωγή περιλαμβάνει ελεγχόμενες ζυμώσεις, ενώ επιλεγμένες ετικέτες ωριμάζουν σε δρύινα βαρέλια και αμφορείς. Για το ΚΤΗΜΑ, το εμβληματικό Αγιωργίτικο του κτήματος, η πρώτη ύλη προέρχεται από επιλεγμένους αμπελώνες στο Κούτσι Νεμέας, σε υψόμετρο περίπου 700 μέτρων, και το κρασί ωριμάζει για 16 μήνες σε γαλλική δρυ.",
  "Παράλληλα, ετικέτες όπως το THESIS και το Rarus K εκφράζουν την επιθυμία του Κτήματος να εξερευνά διαφορετικές εκφράσεις των ελληνικών ποικιλιών, διατηρώντας ως σταθερό σημείο αναφοράς τον τόπο και την ποιότητα της πρώτης ύλης.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "bairaktaris" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story (αντικαταστάθηκε) + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
