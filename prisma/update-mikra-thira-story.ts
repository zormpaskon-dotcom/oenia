import { prisma } from "../lib/prisma";

const story = [
  "Η Μικρά Θήρα είναι το πρώτο οινοποιείο της Θηρασιάς, ενός μικρού νησιού με ακατέργαστη φυσική ομορφιά και ιδιαίτερο μικροκλίμα. Βρίσκεται στις Κυκλάδες, ακριβώς απέναντι από τη Σαντορίνη, της οποίας αποτελούσε κομμάτι μέχρι τη μεγάλη ηφαιστειακή έκρηξη του 17ου αιώνα π.Χ.",
  "Η Θηρασιά παρουσιάζει παρόμοια χαρακτηριστικά στο μικροκλίμα της με αυτά της Σαντορίνης, που αποδεδειγμένα εγγυώνται την παραγωγή ποιοτικών κρασιών με αυθεντικό χαρακτήρα.",
  "Το ηφαιστιογενές έδαφος, οι αυτόφυτες ρίζες, οι δυνατοί άνεμοι και οι σπάνιες βροχοπτώσεις είναι στοιχεία που συνθέτουν ένα ξεχωριστό περιβάλλον. Παράλληλα, το παραδοσιακό σύστημα διαμόρφωσης των κλημάτων σε σχήμα «κουλούρας» θεωρείται μοναδικό στον κόσμο.",
  "Αυτό που κάνει τη Θηρασιά να ξεχωρίζει είναι πως πρόκειται για ένα παρθένο φυσικό περιβάλλον, με ελάχιστα σημάδια παρέμβασης, έτοιμο να προσφέρει τον πλούτο του σε όποιον το καλλιεργήσει μεθοδικά και μετρημένα.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "mikra-thira" },
    data: { story },
  });
  console.log(`✓ ${winery.name} -> story updated (${story.length} chars)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
