// Κείμενο story για το Aoton Winery, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στην καρδιά της Παιανίας, στο Παλαιό Χωριό των Μεσογείων, το Aoton Winery διατηρεί μια βαθιά σχέση με την αμπελουργική παράδοση της Αττικής. Η οικογενειακή παράδοση συνεχίζεται σήμερα από τον οινολόγο Σωτήριο Γκίνη, με το οινοποιείο να παραμένει συνδεδεμένο με τον χαρακτήρα και την ταυτότητα του μεσογείτικου αμπελώνα.",
  "Στους οικογενειακούς βιολογικούς αμπελώνες καλλιεργούνται κυρίως οι ελληνικές ποικιλίες Σαββατιανό, Ροδίτης και Μανδηλαριά, μαζί με Cabernet Sauvignon. Το Σαββατιανό κατέχει ξεχωριστή θέση, σε μια περιοχή όπου η ιστορία της ποικιλίας συνδέεται με χιλιάδες χρόνια αμπελουργικής παράδοσης.",
  "Το οινοποιείο βρίσκεται μέσα στον παραδοσιακό οικισμό της Παιανίας και έχει σχεδιαστεί με στόχο την παραγωγή κρασιών Προστατευόμενης Γεωγραφικής Ένδειξης, συνδυάζοντας την παράδοση των Μεσογείων με μια σύγχρονη προσέγγιση στην οινοποίηση.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "aoton-winery" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
