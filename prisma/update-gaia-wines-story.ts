// Κείμενο story για το Gaia Wines, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Η Gaia Wines ιδρύθηκε το 1994 από τον Γιάννη Παρασκευόπουλο και τον Λέοντα Καράτσαλο, με μια ξεκάθαρη επιλογή από την αρχή: να εγκαταστήσουν τη δραστηριότητά τους σε δύο από τις σημαντικότερες αμπελουργικές περιοχές της Ελλάδας, τη Νεμέα και τη Σαντορίνη, και να εξερευνήσουν σε βάθος τις δυνατότητες των ελληνικών ποικιλιών.",
  "Στη Νεμέα, το οινοποιείο βρίσκεται στο Κούτσι, σε υψόμετρο 550 μέτρων, μέσα σε ιδιόκτητο αμπελώνα. Τα φτωχά ασβεστολιθικά εδάφη, οι κλίσεις και οι πιο δροσερές συνθήκες της περιοχής δημιουργούν ένα περιβάλλον που αναδεικνύει το Αγιωργίτικο, την κεντρική ερυθρή ποικιλία της περιοχής. Στη Σαντορίνη, το Ασύρτικο εκφράζεται μέσα από το ηφαιστειακό έδαφος, τους ισχυρούς ανέμους και την πανάρχαια αμπελουργική παράδοση του νησιού.",
  "Από τον ΘΑΛΑΣΣΙΤΗ και το ΚΤΗΜΑ ΓΑΙΑΣ έως τις πιο πειραματικές οινοποιήσεις, η Gaia Wines έχει διατηρήσει ως σταθερό άξονα την εξερεύνηση του βάθους των ελληνικών ποικιλιών. Η παράδοση λειτουργεί ως αφετηρία, ενώ η έρευνα και η σύγχρονη οινοποίηση ως εργαλεία για την εξέλιξή τους.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "gaia-wines" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
