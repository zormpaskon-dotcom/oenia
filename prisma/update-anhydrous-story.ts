// Κείμενο story για το Anhydrous Winery, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στη Σαντορίνη, το Anhydrous Winery αποτελεί το προσωπικό οινοποιητικό εγχείρημα του Απόστολου Μούντριχα, που ξεκίνησε το 2012 από τη βαθιά σχέση του με το νησί και ιδιαίτερα με το Ασύρτικο. Το 2021, μετά από σχεδόν μία δεκαετία έρευνας και δημιουργίας, ιδρύθηκε το Anhydrous Winery με στόχο την παραγωγή σύγχρονων κρασιών που διατηρούν την καθαρότητα και τον πρωτογενή χαρακτήρα της ποικιλίας.",
  "Η φιλοσοφία του οινοποιείου βασίζεται στην ανάδειξη του ηφαιστειακού μικροκλίματος και της τυπικότητας του σαντορινιού terroir. Τα αμμώδη ηφαιστειακά εδάφη, με λάβα και ελαφρόπετρα, η έντονη ηλιοφάνεια, τα Μελτέμια και η χαμηλή βροχόπτωση δημιουργούν ένα απαιτητικό αλλά ιδιαίτερο περιβάλλον για την αμπέλου. Τα παραδοσιακά αμπέλια διαμορφώνονται σε κουλούρες, ενώ στο επίκεντρο βρίσκονται το Ασύρτικο, το Αθήρι, το Αηδάνι, η Μανδηλαριά και το Μαυροτράγανο.",
  "Η οινοποίηση συνδυάζει τον πειραματισμό με αρχαίες τεχνικές και τη σύγχρονη τεχνογνωσία, με στόχο κρασιά που εκφράζουν με ακρίβεια τον τόπο, την ποικιλία και τη μοναδική φυσιογνωμία της Σαντορίνης.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "anhydrous-winery" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
