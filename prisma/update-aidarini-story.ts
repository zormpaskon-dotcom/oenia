// Κείμενο story για το Οινοποιεία Αϊδαρίνη, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στη Γουμένισσα Κιλκίς, στους πρόποδες του Πάικου, το Οινοποιείο Αϊδαρίνη αποτελεί μια από τις ιστορικές οικογένειες του μακεδονικού αμπελώνα. Η οικογένεια ασχολείται με την παραγωγή κρασιού και τσίπουρου από τα τέλη του 19ου αιώνα, διατηρώντας μέχρι σήμερα ζωντανή τη σύνδεσή της με την οινική παράδοση της περιοχής. Στην αίθουσα γευστικών δοκιμών φυλάσσονται μάλιστα χειρόγραφα του προπάππου της οικογένειας που χρονολογούνται από το 1880.",
  "Σήμερα, την οικογενειακή επιχείρηση ηγείται ο Χρήστος Αϊδαρίνης. Το οινοποιείο διαθέτει ιδιόκτητους αμπελώνες και συνεργάζεται σταθερά με αμπελουργούς της ζώνης ΠΟΠ Γουμένισσα, ενώ έχει δημιουργήσει σύγχρονες εγκαταστάσεις στην είσοδο της πόλης, δίπλα στο παραδοσιακό κελάρι της οικογένειας.",
  "Στο επίκεντρο βρίσκεται το Ξινόμαυρο, μαζί με τη Νεγκόσκα, τις δύο γηγενείς ποικιλίες που συνθέτουν τον χαρακτήρα της Γουμένισσας. Η οικογένεια τις αξιοποιεί τόσο στην κλασική έκφραση της ΠΟΠ Γουμένισσα όσο και σε επιλεγμένες εμφιαλώσεις από συγκεκριμένους αμπελώνες, ενώ καλλιεργούνται επίσης λευκές και διεθνείς ποικιλίες.",
  "Η φιλοσοφία του Αϊδαρίνη συνδυάζει τη διατήρηση της οικογενειακής παράδοσης με τη συνεχή ποιοτική εξέλιξη, έχοντας ως σημείο αναφοράς τον αμπελώνα της Γουμένισσας και τις ιδιαίτερες ποικιλίες του.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "oinopoieia-aidarini" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
