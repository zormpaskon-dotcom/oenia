import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στο Κορακοχώρι της Δυτικής Πελοποννήσου, λίγα χιλιόμετρα από τον Πύργο και την Αρχαία Ολυμπία, το Κτήμα Μερκούρη αποτελεί ένα από τα ιστορικά οινοποιεία της περιοχής, με παρουσία που ξεκινά από το 1864.",
  "Η ιστορία του αμπελώνα ξεκίνησε λίγα χρόνια μετά την ίδρυση του κτήματος, με τη φύτευση μοσχευμάτων Ρεφόσκο, ποικιλίας που μεταφέρθηκε από το Friuli της βόρειας Ιταλίας. Ήδη από τα τέλη του 19ου αιώνα, τα κρασιά του Κτήματος Μερκούρη ταξίδευαν εκτός Ελλάδας, φτάνοντας στις ευρωπαϊκές αγορές.",
  "Το 1930 κατασκευάστηκε μέσα στο κτήμα ένα σύγχρονο για την εποχή του οινοποιείο, με υπόγειες δεξαμενές συνολικής χωρητικότητας περίπου 300 τόνων. Η εγκατάσταση παρέμεινε σε λειτουργία έως το 1960, πριν η οικογένεια επαναφέρει σταδιακά την οινοποιητική δραστηριότητα.",
  "Από το 1987, η οικογένεια ανέλαβε την αναβίωση και τον εκσυγχρονισμό του κτήματος. Οι παλιές εγκαταστάσεις ανασυγκροτήθηκαν, οι αμπελώνες ανανεώθηκαν και επεκτάθηκαν, ενώ το 1992 το Κτήμα Μερκούρη απέκτησε τη σημερινή εταιρική του μορφή.",
  "Σήμερα, η Κτήμα Μερκούρη Α.Ε. παραμένει οικογενειακή υπόθεση, με τη διοίκηση να βρίσκεται στα χέρια των αδελφών Βασίλη και Χρήστου Κανελλακόπουλου.",
  "Μια ιστορία που συνδέει περισσότερους από ενάμιση αιώνα αμπελουργικής παράδοσης με τη σύγχρονη ελληνική οινοποίηση.",
].join("\n\n");

async function main() {
  await prisma.winery.update({
    where: { slug: "ktima-merkouri" },
    data: { story: STORY },
  });
  console.log("✓ ktima-merkouri: story updated");
}
main().finally(() => prisma.$disconnect());
