// Editorial fix βάσει external verification: σε 2 wineries η περιγραφή
// έγραφε "βιοδυναμική" ως ισοδύναμη, πιστοποιημένη-ηχούσα δήλωση δίπλα στο
// certified organic claim, ενώ οι πηγές υποστηρίζουν μόνο πρακτικές/effort,
// όχι πιστοποίηση. Καμία αλλαγή σε isOrganic/isBiodynamic/story — μόνο το
// συγκεκριμένο απόσπασμα του description. Domaine Karanika δεν αγγίζεται
// καθόλου (το verification έκρινε το υπάρχον wording ήδη ασφαλές).
// Επαληθεύει το ΑΚΡΙΒΕΣ τρέχον description πριν γράψει.

import { prisma } from "../lib/prisma";

const FIXES: { slug: string; from: string; to: string }[] = [
  {
    slug: "kontozisis-organic-vineyards",
    from: "Ο Ανδρέας Κοντοζήσης, με τον πατέρα και τον αδερφό του, ίδρυσε το κτήμα το 1991 στους πρόποδες των Αγράφων στην Καρδίτσα, αρχικά για να τροφοδοτεί το οικογενειακό εστιατόριο, φυτεύοντας, αναβιώνοντας και ανακαλύπτοντας πάνω από εκατό μικρά, εγκαταλελειμμένα χωράφια. Από τους πρώτους στην Ελλάδα που πιστοποιήθηκαν βιολογικοί, καλλιεργεί σήμερα 11 εκτάρια βιολογικά και βιοδυναμικά, με έμφαση στη σπάνια γηγενή Λημνιώνα.",
    to: "Ο Ανδρέας Κοντοζήσης, με τον πατέρα και τον αδερφό του, ίδρυσε το κτήμα το 1991 στους πρόποδες των Αγράφων στην Καρδίτσα, αρχικά για να τροφοδοτεί το οικογενειακό εστιατόριο, φυτεύοντας, αναβιώνοντας και ανακαλύπτοντας πάνω από εκατό μικρά, εγκαταλελειμμένα χωράφια. Από τους πρώτους στην Ελλάδα που πιστοποιήθηκαν βιολογικοί, καλλιεργεί σήμερα 11 εκτάρια βιολογικά, με βιοδυναμικές πρακτικές, και έμφαση στη σπάνια γηγενή Λημνιώνα.",
  },
  {
    slug: "dalamaras",
    from: "Οικογενειακός αμπελώνας από το 1840 — σήμερα ο Κωστής Δαλαμάρας (6η γενιά, σπούδασε οινολογία στο Beaune) συνεχίζει με τη σύζυγό του Μαρία. Βιολογική καλλιέργεια από το 1996, βιοδυναμική από το 2008, με ίδια ενέργεια από ηλιακά.",
    to: "Οικογενειακός αμπελώνας από το 1840 — σήμερα ο Κωστής Δαλαμάρας (6η γενιά, σπούδασε οινολογία στο Beaune) συνεχίζει με τη σύζυγό του Μαρία. Βιολογική καλλιέργεια από το 1996, με βιοδυναμικές πρακτικές από το 2008, με ίδια ενέργεια από ηλιακά.",
  },
];

async function main() {
  for (const fix of FIXES) {
    const winery = await prisma.winery.findUnique({ where: { slug: fix.slug }, select: { id: true, description: true } });
    if (!winery) throw new Error(`Winery not found: ${fix.slug}`);
    if (winery.description !== fix.from) {
      throw new Error(`Winery "${fix.slug}" description δεν ταιριάζει με το αναμενόμενο — abort χωρίς αλλαγές.\nΤρέχον: ${JSON.stringify(winery.description)}`);
    }
    await prisma.winery.update({ where: { id: winery.id }, data: { description: fix.to } });
    console.log(`✓ Winery "${fix.slug}" description ενημερώθηκε.`);
  }
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
