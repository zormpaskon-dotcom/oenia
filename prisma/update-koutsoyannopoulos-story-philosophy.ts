// Κείμενο story + philosophy για το Koutsoyannopoulos Winery & Museum, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Η ιστορία της οικογένειας Κουτσογιαννόπουλου στη Σαντορίνη ξεκινά το 1870, όταν οι αδελφοί Γρηγόριος και Δημήτριος έφτασαν στο νησί από τους Μολάους Λακωνίας. Αρχικά δραστηριοποιήθηκαν στο εμπόριο, όμως σύντομα αναγνώρισαν τη δυναμική του σαντορινιού αμπελώνα και στράφηκαν στην καλλιέργεια της αμπέλου και την παραγωγή κρασιού. Η οικογενειακή δραστηριότητα αναπτύχθηκε ιδιαίτερα μέσα από το εμπόριο σαντορινιών κρασιών, με σημαντικές αγορές στη Ρωσία και αργότερα στη Δυτική Ευρώπη.",
  "Το 1970 η οικογένεια απέκτησε τον πρώτο ηλεκτρικό εξοπλισμό οινοποίησης και ξεκίνησε σταδιακά την εμφιάλωση, με τις πρώτες ετικέτες VOLCAN και LAVA. Η τεχνολογική εξέλιξη συνεχίστηκε, χωρίς να χαθεί η σύνδεση με την οικογενειακή παράδοση.",
  "Σήμερα, την οικογενειακή συνέχεια εκπροσωπεί η τέταρτη γενιά, ενώ η πέμπτη γενιά έχει ήδη μπει στην ιστορία του κτήματος. Παράλληλα με το οινοποιείο, η οικογένεια δημιούργησε ένα μοναδικό Μουσείο Οίνου σε φυσική υπόγεια σπηλιά, αφιερωμένο στην ιστορία της αμπελουργίας και της οινοποίησης στη Σαντορίνη.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία του Οινοποιείου Κουτσογιαννόπουλου στηρίζεται στη συνύπαρξη της οικογενειακής παράδοσης με τη σύγχρονη τεχνολογία. Η εμπειρία περισσότερων από τεσσάρων γενεών στην αμπελουργία και την οινοποίηση λειτουργεί ως βάση, ενώ ο σύγχρονος εξοπλισμός χρησιμοποιείται για τη διατήρηση και τη βελτίωση της ποιότητας των κρασιών. Η παραγωγή βασίζεται στους ιδιόκτητους αμπελώνες της οικογένειας και στην εκτενή γνώση των τοπικών ποικιλιών της Σαντορίνης.",
  "Η διατήρηση της οινικής κληρονομιάς αποτελεί εξίσου σημαντικό μέρος της ταυτότητας του κτήματος. Το Μουσείο Οίνου δημιουργήθηκε σε φυσική σπηλιά, οκτώ μέτρα κάτω από την επιφάνεια της γης και με μήκος περίπου 300 μέτρων. Για την ολοκλήρωσή του χρειάστηκαν 21 χρόνια εργασίας και η χρηματοδότηση έγινε εξ ολοκλήρου από την οικογένεια.",
  "Το αποτέλεσμα είναι κάτι περισσότερο από ένας χώρος παραγωγής κρασιού. Το οινοποιείο λειτουργεί παράλληλα ως φορέας διατήρησης της ιστορίας του σαντορινιού αμπελώνα, παρουσιάζοντας την εξέλιξη της αμπελουργίας και της οινοποίησης από τον 17ο αιώνα έως την εποχή της τεχνολογικής μετάβασης. Έτσι, η σημερινή παραγωγή συνδέεται άμεσα με τη μνήμη, τον τόπο και την οινική κουλτούρα της Σαντορίνης.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "koutsoyannopoulos-winery" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
