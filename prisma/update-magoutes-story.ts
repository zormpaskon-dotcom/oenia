// Κείμενο story για το Magoutes Vineyard, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στη Σιάτιστα της Κοζάνης, σε ένα από τα πιο ορεινά και ιδιαίτερα αμπελουργικά τοπία της Δυτικής Μακεδονίας, το Magoutes Vineyard αποτελεί μια προσπάθεια αναβίωσης μιας μακράς τοπικής οινικής παράδοσης. Η αμπελουργική ιστορία της περιοχής εκτείνεται τουλάχιστον τρεις αιώνες πίσω, ενώ το σημερινό εγχείρημα γεννήθηκε από τον Δημήτρη Διαμαντή και τον Γιώργο Παπαγεωργίου, με κοινό στόχο να διατηρήσουν και να αναδείξουν το αμπελουργικό δυναμικό του τόπου.",
  "Οι αμπελώνες βρίσκονται σε μεγάλο υψόμετρο, περίπου 750–890 μέτρα, σε φτωχά ασβεστολιθικά εδάφη και ένα ψυχρό, ξηρό ηπειρωτικό κλίμα. Στο επίκεντρο βρίσκονται το Ξινόμαυρο και το Μοσχόμαυρο, μαζί με το Νιγρικιώτικο, ποικιλίες που συνδέονται με την παλαιότερη αμπελουργική παράδοση της Σιάτιστας.",
  "Η καλλιέργεια και η οινοποίηση πραγματοποιούνται σε μικρή κλίμακα, με περιορισμένες παρεμβάσεις και αυθόρμητες ζυμώσεις, χωρίς τη χρήση ενζύμων ή διαυγαστικών. Η πρώτη επίσημη εμφιάλωση πραγματοποιήθηκε το 2002 και από τότε το Magoutes Vineyard έχει ως σταθερό στόχο να αφήνει το συγκεκριμένο terroir και τις τοπικές ποικιλίες να εκφράζονται με καθαρότητα και ακρίβεια.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "magoutes-vineyard" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
