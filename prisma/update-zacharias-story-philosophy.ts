// Κείμενο story + philosophy για το Zacharias Winery, δόθηκε αυτούσιο από τον χρήστη
// (χωρίς τα inline citation links του αρχικού κειμένου, όπως ζητήθηκε).
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στη Νεμέα, στους αμπελώνες που απλώνονται γύρω από το Λεόντιο και τις πλαγιές της περιοχής, η Zacharias Winery έχει συνδέσει την πορεία της με την εξέλιξη του Αγιωργίτικου και του πελοποννησιακού αμπελώνα. Η σύγχρονη ιστορία της οινοποιίας ξεκινά το 1974, όταν η οικογένεια άρχισε να επενδύει συστηματικά στην παραγωγή και στην ποιοτική αναβάθμιση των κρασιών της Νεμέας.",
  "Σήμερα, η οικογένεια διαθέτει περίπου 40 εκτάρια αμπελώνων, από τα οποία περίπου 30 βρίσκονται στην ευρύτερη περιοχή της Νεμέας και περίπου 10 στη Μαντινεία. Σημαντικό μέρος των αμπελώνων βρίσκεται στις πλαγιές γύρω από το Λεόντιο, σε υψόμετρα που συνολικά εκτείνονται περίπου από 200 έως 850 μέτρα.",
  "Το Αγιωργίτικο αποτελεί τον βασικό άξονα της παραγωγής, ενώ το κτήμα καλλιεργεί συνολικά 13 ποικιλίες, ανάμεσα στις οποίες βρίσκονται Ασύρτικο, Μοσχοφίλερο, Ροδίτης, Μαλαγουζιά, Μαυροδάφνη, Cabernet Sauvignon, Merlot, Chardonnay και Syrah. Η παραγωγή περιλαμβάνει κρασιά ΠΟΠ Νεμέα και ΠΓΕ Πελοπόννησος, ενώ η οικογένεια συνεχίζει να επενδύει στην αξιοποίηση διαφορετικών υψομέτρων και ποικιλιών του πελοποννησιακού αμπελώνα.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία της Zacharias Winery έχει ως βασικό σημείο αναφοράς την προστασία και την ανάδειξη των ποικιλιών και των αμπελουργικών ζωνών της Πελοποννήσου. Η οικογένεια δίνει ιδιαίτερη έμφαση στο Αγιωργίτικο και στη ζώνη ΠΟΠ Νεμέα, θεωρώντας την ποικιλία και τον τόπο αναπόσπαστα στοιχεία της ταυτότητας των κρασιών της.",
  "Οι αμπελώνες εκτείνονται σε σημαντικό υψομετρικό εύρος, από περίπου 200 έως 850 μέτρα. Η διαφορά ανάμεσα στις πεδινές, ημιορεινές και ορεινές θέσεις δημιουργεί διαφορετικούς χρόνους ωρίμασης και διαφορετικά χαρακτηριστικά στην πρώτη ύλη, γεγονός που επιτρέπει στην οινοποιία να αξιοποιεί διαφορετικές εκφράσεις του Αγιωργίτικου.",
  "Η καλλιέργεια πραγματοποιείται με σύστημα ολοκληρωμένης περιβαλλοντικής διαχείρισης, με έμφαση στις περιορισμένες αποδόσεις και στον σεβασμό προς τη φύση και τον άνθρωπο. Η ίδια η Zacharias θέτει ως στόχο τη διατήρηση και διάδοση των ποικιλιών των ζωνών ΠΟΠ Νεμέα και ΠΓΕ Πελοπόννησος, ως μέρος της πολιτιστικής κληρονομιάς της περιοχής.",
  "Στο οινοποιείο, οι μέθοδοι προσαρμόζονται στο στυλ κάθε κρασιού. Για παράδειγμα, η Nemea Zacharias παράγεται από 100% Αγιωργίτικο, με ψυχρή εκχύλιση, ελεγχόμενη ζύμωση και ωρίμαση σε γαλλικά δρύινα βαρέλια δεύτερης και τρίτης χρήσης. Η προσέγγιση παραμένει προσανατολισμένη στον τόπο, στην ποικιλία και στη συνεχή βελτίωση της ποιότητας.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "zacharias-winery" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
