// Κείμενο story για το Argyriou Winery, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στο Πολύδροσο Παρνασσού, στους πρόποδες του ορεινού όγκου, το Κτήμα Αργυρίου έχει χτίσει την ταυτότητά του γύρω από τον αμπελώνα και το ιδιαίτερο terroir της περιοχής. Η ιστορία του ξεκίνησε το 1998, όταν ο Νίκος Αργυρίου δημιούργησε τους πρώτους αμπελώνες, θέλοντας να αναδείξει τις δυνατότητες της γης του Παρνασσού.",
  "Σήμερα το κτήμα διαθέτει περίπου 300 στρέμματα ιδιόκτητων αμπελώνων, σε υψόμετρο 400–550 μέτρων, με αργιλώδη εδάφη και ξηρό κλίμα. Καλλιεργούνται ελληνικές ποικιλίες όπως το Μαυρούδι, ο Ροδίτης, η Ρομπόλα, το Ασύρτικο και η Μαλαγουζιά, μαζί με διεθνείς ποικιλίες όπως Sauvignon Blanc, Chardonnay, Merlot, Cabernet Sauvignon και Pinot Noir.",
  "Η οινοποίηση συνδυάζει σύγχρονες μεθόδους με βιώσιμες πρακτικές στον αμπελώνα, ενώ ιδιαίτερη θέση έχει το Μαυρούδι, μια ποικιλία που ο Νίκος Αργυρίου ανέδειξε ξανά μέσα από χρόνια πειραματισμού. Το οινοποιείο φιλοξενεί επίσης χώρο γευσιγνωσίας, συνδέοντας το κρασί με την εμπειρία του Παρνασσού.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "argyriou-winery" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
