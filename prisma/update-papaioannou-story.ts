// Κείμενο story για το Estate Papaioannou, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στην Αρχαία Νεμέα, το Κτήμα Παπαϊωάννου αποτελεί μια οικογενειακή οινοποιητική ιστορία με ρίζες από το 1876 και μια από τις πιο σταθερές παρουσίες στον σύγχρονο αμπελώνα της Νεμέας. Ο Θανάσης Παπαϊωάννου υπήρξε από τους παραγωγούς που ανέδειξαν την ανάγκη το κρασί να εκφράζει την ποικιλία, τη συγκεκριμένη θέση του αμπελώνα και τον τρόπο καλλιέργειας, αντί να ακολουθεί ένα ενιαίο πρότυπο.",
  "Σήμερα, η οικογένεια διαθέτει περίπου 57 εκτάρια ιδιόκτητων αμπελώνων σε διαφορετικές θέσεις της ζώνης της Νεμέας, με διαφορετικά οικοσυστήματα, υψόμετρα και ηλικίες φυτεύσεων. Η καλλιέργεια ακολουθεί βιολογικές πρακτικές και η επιλογή της ποικιλίας γίνεται ανάλογα με τα χαρακτηριστικά κάθε αμπελοτεμαχίου.",
  "Στο επίκεντρο βρίσκεται το Αγιωργίτικο, πλαισιωμένο από Cabernet Sauvignon, Ροδίτη, Ασύρτικο, Chardonnay, Pinot Noir, Syrah, Merlot, Touriga, Roussanne, Sauvignon Blanc και Petit Verdot. Ο Γιώργος Παπαϊωάννου, χημικός και οινολόγος, συνεχίζει σήμερα την οικογενειακή διαδρομή, συνδυάζοντας τη γνώση του αμπελώνα με τη σύγχρονη οινοποίηση και τον συνεχή πειραματισμό.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "papaioannou-estate" },
    data: { story: STORY },
  });
  console.log(`✓ ${winery.name}: story ενημερώθηκε (${STORY.length} χαρακτήρες)`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
