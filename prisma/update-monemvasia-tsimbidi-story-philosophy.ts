// Κείμενο story + philosophy για το Monemvasia Winery Tsimbidi, δόθηκε αυτούσιο από τον χρήστη.
import { PrismaClient } from "@prisma/client";
const prisma = new PrismaClient();

const STORY = [
  "Στη Μονεμβασιά Λακωνίας, η Οινοποιητική Μονεμβασιάς δημιουργήθηκε το 1997 από τον Γιώργο και την Έλλη Τσιμπίδη, με ένα φιλόδοξο όραμα: να επαναφέρει στο προσκήνιο τον χαμένο ιστορικό αμπελώνα της περιοχής και να αναβιώσει το θρυλικό κρασί Μονεμβασία-Malvasia. Η προσπάθεια ξεκίνησε από την έρευνα και την καταγραφή των γηγενών ποικιλιών της περιοχής, σε συνεργασία με πανεπιστημιακούς και ερευνητικούς φορείς.",
  "Για περισσότερα από δώδεκα χρόνια πραγματοποιήθηκαν πειραματικές φυτεύσεις, οινοποιήσεις και μελέτες γύρω από τις τοπικές ποικιλίες και την ιστορική ταυτότητα του Malvasia. Η προσπάθεια οδήγησε το 2010 στην αναγνώριση του Μονεμβασία-Malvasia ως ΠΟΠ και, το 2013, στην πρώτη του εμφιάλωση.",
  "Παράλληλα, η οικογένεια δημιούργησε έναν σύγχρονο αμπελώνα με γηγενείς ποικιλίες όπως Μονεμβασιά, Κυδωνίτσα, Ασπρούδι, Μαυρούδι και Ασύρτικο. Το νέο οινοποιείο ολοκληρώθηκε το 2020 και στεγάζει τόσο την παραγωγή όσο και τις δραστηριότητες οινοτουρισμού.",
].join("\n\n");

const PHILOSOPHY = [
  "Η φιλοσοφία της Monemvasia Winery Tsimbidi ξεκινά από τον ίδιο τον τόπο. Η οικογένεια Τσιμπίδη επέλεξε από την αρχή να επενδύσει αποκλειστικά στις ελληνικές και ιδιαίτερα στις γηγενείς ποικιλίες της περιοχής, αναζητώντας μέσα από αυτές τον χαρακτήρα και το δυναμικό του μονεμβασιώτικου terroir.",
  "Η έρευνα αποτέλεσε βασικό εργαλείο αυτής της προσέγγισης. Η μελέτη δεκατεσσάρων τοπικών ποικιλιών, οι πειραματικές οινοποιήσεις και η συνεργασία με επιστημονικούς φορείς οδήγησαν στην αναβίωση παλαιών ποικιλιών και στην καλύτερη κατανόηση του αμπελώνα της περιοχής. Σήμερα, η οικογένεια καλλιεργεί οργανικούς αμπελώνες στις Βελιές και τον Άγιο Δημήτριο, με έμφαση στις ποικιλίες που εκφράζουν τοπικά χαρακτηριστικά.",
  "Ξεχωριστή θέση κατέχει το Μονεμβασία-Malvasia. Η παραγωγή του βασίζεται σε υπερώριμα σταφύλια που λιάζονται για περίπου δώδεκα ημέρες, ενώ το κρασί στη συνέχεια ωριμάζει για δύο χρόνια σε παλιά δρύινα βαρέλια.",
  "Η προσέγγιση του οινοποιείου συνδυάζει έτσι την ιστορική έρευνα, την οργανική αμπελουργία και τη σύγχρονη οινοποίηση, με σταθερό σημείο αναφοράς την ανάδειξη της Μονεμβασιάς μέσα από τις δικές της ποικιλίες και το ιδιαίτερο τοπίο της.",
].join("\n\n");

async function main() {
  const winery = await prisma.winery.update({
    where: { slug: "monemvasia-winery-tsimbidi" },
    data: { story: STORY, philosophy: PHILOSOPHY },
  });
  console.log(`✓ ${winery.name}: story + philosophy ενημερώθηκαν`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
